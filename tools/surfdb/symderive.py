def derived_for(slug):
    """The frozen derivation for a slug, or None."""
    got = DERIVED.get(slug)
    return dict(got) if got else None


def _selftest():
    """Calibrate against the three surfaces with published groups."""
    sg = _spacegroups()

    # The standard nodal approximants, as the records store them.
    P = "cos(x) + cos(y) + cos(z)"
    G = "sin(x) * cos(y) + sin(y) * cos(z) + sin(z) * cos(x)"
    N = "3 * (cos(x) + cos(y) + cos(z)) + 4 * cos(x) * cos(y) * cos(z)"
    D = ("sin(x) * sin(y) * sin(z) + sin(x) * cos(y) * cos(z)"
         " + cos(x) * sin(y) * cos(z) + cos(x) * cos(y) * sin(z)")

    # POSITIVE CONTROLS: the published group must come out, and it must
    # come out as the MAXIMAL one -- a method that merely finds *a*
    # subgroup would pass a weaker test while being useless.
    for text, want in ((P, "Im-3m"), (G, "Ia-3d"), (N, "Im-3m")):
        got = derive(text)
        if got["hermann_mauguin"] != want:
            raise AssertionError("expected %s, derived %s"
                                 % (want, got["hermann_mauguin"]))

    # NEGATIVE CONTROL: the patch-tiling subgroup must NOT be reported.
    # Pm-3m holds for P, and reporting it would be the exact error that
    # deriving from evolver_cell.generators makes.
    if not satisfies(P, sg.ops("Pm-3m")):
        raise AssertionError("Pm-3m should hold for P (it is a subgroup)")
    if derive(P, candidates=("Pm-3m", "Im-3m"))["hermann_mauguin"] != "Im-3m":
        raise AssertionError("the maximal group must win over its subgroup")

    # THE RECORDED DISAGREEMENT: D satisfies Fd-3m and no setting of its
    # published Pn-3m, and its maximal order is held by THREE distinct
    # groups at once, so the derivation must report an ambiguity rather
    # than pick one.  Pinned so that if it ever changes, someone looks.
    got = derive(D)
    if not got["ambiguous"] or got["hermann_mauguin"] is not None:
        raise AssertionError("D must come back ambiguous, got %r" % (got,))
    if satisfies(D, sg.ops("Pn-3m:2")):
        raise AssertionError("Pn-3m unexpectedly holds for D at the origin")
    if not satisfies(D, sg.ops("Fd-3m")):
        raise AssertionError("Fd-3m should hold for D")
    # ...because the D approximant is F-centred; this is the reason.
    fc = satisfies(D, [(((1, 0, 0), (0, 1, 0), (0, 0, 1)), (6, 6, 0))])
    if not fc:
        raise AssertionError("D should be invariant under (1/2, 1/2, 0)")

    # A function with NO symmetry must derive nothing rather than
    # something: an oracle that always answers is not an oracle.
    if derive("cos(x) + 0.3137 * cos(2 * y) + 0.717 * sin(3 * z)",
              candidates=("Im-3m", "Ia-3d", "Fd-3m", "Pn-3m:2"),
              )["hermann_mauguin"] is not None:
        raise AssertionError("a lopsided function must not match a group")

    # THE FROZEN TABLE MUST STILL MATCH THE CODE. Re-derive a sample --
    # one resolved row and one ambiguous row -- so a change to the
    # method or to spacegroups.py cannot leave a stale table behind.
    if DERIVED["schwarz-p"]["hermann_mauguin"] != "Im-3m":
        raise AssertionError("frozen table disagrees with the calibration")
    if not DERIVED["schwarz-d"]["ambiguous"]:
        raise AssertionError("D must be frozen as ambiguous")
    live = derive(P)
    if live["hermann_mauguin"] != DERIVED["schwarz-p"]["hermann_mauguin"]:
        raise AssertionError("frozen table is stale for schwarz-p")

    print("RESULT: OK  (surfdb.symderive, %d rows frozen, 3 published "
          "groups reproduced, " % len(DERIVED) +
          "subgroup rejected, tie detected, unsymmetric function refused)")
