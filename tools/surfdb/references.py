# Citations, harvested from the module headers that already carry them.
#
# The contributor notes require every generator module in math_art/ to
# credit the
# mathematics it implements in a `References:` block -- the mathematician,
# the paper or book, the year.  Those blocks are vetted, they are kept
# current by whoever writes the generator, and `docs/scaffold_pages.py`
# already lifts them verbatim onto the documentation pages.
#
# So the surface database should not retype them from memory.  Retyping
# is how a citation becomes subtly wrong, and a wrong citation is worse
# than none: it looks authoritative.  This module reads the blocks
# instead, which means a record's provenance stays in step with the code
# for free.
#
# TWO REFINEMENTS over the docs extractor.
#
# 1. MULTIPLE BLOCKS PER MODULE.  math_art/minsurf/weierstrass.py carries
#    15 `References:` blocks, zoo.py 8 -- one per family section, each
#    citing the papers for the surfaces defined below it.  Taking only
#    the header would attribute Karcher's saddle towers to the whole zoo.
#    So every block is collected with its line number, and a row is given
#    the NEAREST PRECEDING block, which is the one written about it.
#
# 2. NAME MATCHING.  A row labelled "Wei Doubly Periodic (genus 2)" wants
#    the reference that mentions Wei first.  Surnames in the label are
#    matched against the block's entries and matching ones are promoted,
#    so the most specific citation leads.
#
# Where neither applies the record says so explicitly rather than
# carrying a placeholder -- see `METHOD_ONLY` below.

import os
import re

# The Weierstrass-Enneper representation itself, for rows whose
# individual attribution is not recorded anywhere in the tree.  This is a
# REAL citation of the construction, paired with an explicit statement
# that the individual member is unattributed -- which is information,
# where "not curated yet" is not.
METHOD_ONLY = [
    'K. Weierstrass, "Untersuchungen ueber die Flaechen, deren mittlere '
    'Kruemmung ueberall gleich null ist", Monatsber. Berliner Akad. (1866); '
    'A. Enneper, Zeitschrift fuer Mathematik und Physik 9 (1864) -- the '
    'representation formula this surface is built from.',
    "No individual attribution for this family member is recorded in the "
    "source tree; it is a member of a family generated by the method above "
    "rather than a separately published surface.",
]


def blocks(path):
    """Every `References:` block in `path`, as (line_number, [entries]).

    Entries follow the repo convention: each begins with a `-` marker (or,
    in the older header style, is simply indented) and continuation lines
    are rejoined into it.
    """
    if not path or not os.path.exists(path):
        return []
    out = []
    cur = None
    with open(path, encoding="utf-8", errors="replace") as fh:
        for n, line in enumerate(fh, 1):
            # `References:` and also the sectioned form several modules
            # use -- "References for 5:", "References for 8:" -- which
            # carries real citations and would otherwise be invisible.
            if re.match(r"^#\s*References(\s+for\s+[^:]*)?:", line):
                cur = (n, [])
                out.append(cur)
                continue
            if cur is None:
                continue
            if not line.startswith("#"):
                cur = None
                continue
            body = line[1:].rstrip()
            if not body.strip():
                cur = None
                continue
            text = body.strip()
            starts = text.startswith(("-", "*"))
            text = re.sub(r"^[-*]\s*", "", text)
            entries = cur[1]
            # A line that starts a new entry: an explicit marker, or -- for
            # the older unmarked style -- a line that looks like the start
            # of a citation (an initial-and-surname, or a quoted title).
            looks_new = bool(re.match(r"^[A-Z]\.\s*[A-Z]", text)) or \
                bool(re.match(r"^[A-Z][a-z]+,\s", text))
            if starts or not entries or (looks_new and len(entries[-1]) > 60):
                entries.append(text)
            else:
                entries[-1] += " " + text
    return [(n, [e for e in es if e]) for n, es in out if es]


def header(path):
    """The first block: the module-level references."""
    bs = blocks(path)
    return list(bs[0][1]) if bs else []


def nearest(path, line_no):
    """The block written about the code at `line_no`.

    The nearest block ABOVE the line, falling back to the header. This is
    what makes per-family citation work in a 11,000-line module that
    carries fifteen of them.
    """
    bs = blocks(path)
    if not bs:
        return []
    best = None
    for n, entries in bs:
        if n <= line_no and (best is None or n > best[0]):
            best = (n, entries)
    if best is None:
        best = bs[0]
    return list(best[1])


