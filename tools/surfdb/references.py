def surnames(label):
    """Plausible surnames in a row label, for promoting the right citation."""
    parts = set()
    for tok in re.split(r"[^A-Za-z]+", label or ""):
        if _SURNAME.fullmatch(tok) and tok not in _NOT_NAMES:
            parts.add(tok)
    return parts


def rank(entries, label):
    """Reorder `entries` so those naming the label's surnames come first."""
    names = surnames(label)
    if not names or not entries:
        return list(entries)
    hit, miss = [], []
    for e in entries:
        (hit if any(n in e for n in names) else miss).append(e)
    return hit + miss


def for_row(path, line_no, label, max_entries=6):
    """Citations for one registry row. Empty when the module carries none."""
    got = rank(nearest(path, line_no), label)
    return got[:max_entries]


def _selftest():
    """Parser self-test on a synthetic module; raises on failure."""
    import tempfile
    src = '''# A module.
#
# References:
# - H. F. Scherk, "Bemerkungen", J. reine angew. Math. 13 (1835).
# - K. Weierstrass (1866); A. Enneper (1864).

import math

# References:
# - H. Karcher, "Embedded minimal surfaces derived from Scherk's
#   examples", Manuscripta Math. 62 (1988).
# - M. Wohlgemuth, "Minimal surfaces of higher genus", 1997.

def later():
    pass
'''
    fd, path = tempfile.mkstemp(suffix=".py")
    os.write(fd, src.encode())
    os.close(fd)
    try:
        bs = blocks(path)
        assert len(bs) == 2, bs
        assert len(bs[0][1]) == 2 and len(bs[1][1]) == 2, bs

        # a continuation line must be rejoined, not made its own entry
        assert "Manuscripta Math. 62 (1988)." in bs[1][1][0], bs[1][1]

        h = header(path)
        assert h[0].startswith("H. F. Scherk"), h

        # the NEAREST block wins -- this is what stops Karcher's towers
        # being attributed to the whole module
        near = nearest(path, 200)
        assert near[0].startswith("H. Karcher"), near
        near = nearest(path, 3)
        assert near[0].startswith("H. F. Scherk"), near

        # surname matching promotes the specific citation
        got = for_row(path, 200, "Wohlgemuth Second Surface (genus 3)")
        assert "Wohlgemuth" in got[0], got

        # label noise must not be read as a surname
        assert surnames("Six-Ended Scherk Tower (genus 1)") == {"Scherk"}
        assert surnames("Torus with Catenoid + 2 Annular Ends") == set()
    finally:
        os.unlink(path)

    # against the real tree, if present
    real = os.path.join(os.path.dirname(os.path.dirname(
        os.path.dirname(os.path.abspath(__file__)))), "math_art",
        "minsurf", "weierstrass.py")
    if os.path.exists(real):
        bs = blocks(real)
        assert len(bs) >= 10, \
            "weierstrass.py should carry many per-family blocks, got %d" % len(bs)

    print("RESULT: OK  (surfdb.references)")
