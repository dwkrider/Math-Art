
# Polyhedral Tangle Generator for Blender
#
# Interwoven compounds of polyhedron frames -- "tangles" in the spirit
# of Alan Holden's orderly tangles and the sculptural renders of
# Forging Mind (e.g. "Tetra Tangle" = the compound of five tetrahedra).
# Each component polyhedron is built as hollow-face frames (each face a
# mitred ring with adjustable width and thickness; rings of adjacent
# faces overlap along the edges into ribbed struts, as in Hart's
# five-tetrahedra polylink).
#
# Compounds: 2 tetrahedra (stella octangula), 5 tetrahedra (chiral,
# icosahedral), 10 tetrahedra, 5 cubes, 5 octahedra, 3 cubes
# (octahedral). Components are rotated copies of a seed, generated by
# exact symmetry rotations.
#
# References:
# - Alan Holden, "Orderly Tangles: Cloverleafs, Gordian Knots, and
#   Regular Polylinks", Columbia University Press, 1983.
# - George W. Hart, "Orderly Tangles Revisited" (regular polylinks,
#   e.g. the five-tetrahedra polylink), Bridges 2005.
# - The five-tetrahedra compound / stella octangula are classical
#   polyhedral compounds (see e.g. H. S. M. Coxeter).

