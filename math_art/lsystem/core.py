class Production:
    """One rewriting rule.

    `left`/`right` are context word patterns (symbols only -- context is
    matched on identity, not on parameter values), `strict` is the module
    being replaced together with its FORMAL parameter names, `cond` is an
    optional compiled condition, `succ` is the successor as
    (symbol, [compiled argument expressions]) pairs, and `prob` is the
    stochastic weight.
    """

    __slots__ = ("label", "left", "strict_sym", "formals", "right",
                 "cond", "succ", "prob", "src")

    def __init__(self, label, left, strict_sym, formals, right,
                 cond, succ, prob, src=""):
        self.label = label
        self.left = left
        self.strict_sym = strict_sym
        self.formals = formals
        self.right = right
        self.cond = cond
        self.succ = succ
        self.prob = prob
        self.src = src

    @property
    def contextual(self):
        return bool(self.left or self.right)

    def __repr__(self):
        return f"Production({self.src!r})"


class Param:
    """A knob a grammar declares with `#param`, for a UI to render.

    Carries everything the caller needs to build a control without
    knowing anything about the grammar: the range, the increment the
    author considers meaningful, and a human label.  `value` is what
    this parse actually used, after any override and clamping.
    """

    __slots__ = ("name", "default", "lo", "hi", "step", "label", "value",
                 "choices")

    def __init__(self, name, default, lo, hi, step, label, value,
                 choices=None):
        self.name = name
        self.default = default
        self.lo = lo
        self.hi = hi
        self.step = step
        self.label = label
        self.value = value
        #: ((text, value), ...) when the author declared a fixed set,
        #: else None.  A UI should render these as a menu, not a slider.
        self.choices = tuple(choices) if choices else None

    @property
    def is_choice(self):
        return self.choices is not None

    def snap(self, v):
        """Coerce a value to what the author actually allows: the nearest
        declared choice, or the range rounded to the declared step."""
        v = float(v)
        if self.choices:
            return min((c[1] for c in self.choices), key=lambda c: abs(c - v))
        if self.step:
            base = self.lo if self.lo is not None else 0.0
            v = base + round((v - base) / self.step) * self.step
        if self.lo is not None:
            v = min(max(v, self.lo), self.hi)
        return v

    def text_for(self, v):
        """The label of the choice matching `v`, for a UI or a report."""
        if not self.choices:
            return f"{v:g}"
        for text, val in self.choices:
            if abs(val - float(v)) < 1e-12:
                return text
        return f"{v:g}"

    def __repr__(self):
        if self.choices:
            return (f"Param({self.name}={self.value:g}, "
                    f"choices={[c[0] for c in self.choices]})")
        return (f"Param({self.name}={self.value:g}, "
                f"range=({self.lo}, {self.hi}), step={self.step})")


def _isnum(tok):
    try:
        float(tok)
        return True
    except ValueError:
        return False


class Grammar:
    """A parsed L-system: alphabet, axiom, productions, constants, ignore
    set -- plus the derivation itself."""

    def __init__(self, axiom, productions, constants=None, ignore=(),
                 names=(), mode="parallel", source="", draw=(), angle=None,
                 step=None, iters=None, max_iters=None, closed=False,
                 title=""):
        self.axiom = list(axiom)
        self.productions = list(productions)
        self.constants = dict(constants or {})
        #: `Param` records from `#param`, in declaration order.
        self.params = ()
        #: True if the grammar asked for the developmental series
        #: (`#develop`) -- see `turtle.stack_series`.
        self.develop = False
        self.ignore = set(ignore)
        self.names = tuple(names)
        self.mode = mode
        self.source = source
        # Presentation defaults a preset may carry with it, so the
        # operator does not need a parallel table of magic numbers.
        # `draw` is the set of letters the turtle advances on: the
        # Sierpinski arrowhead and the Gosper curve draw with A and B,
        # not F, so this cannot be a global constant.
        self.draw = frozenset(draw)
        self.angle = angle
        self.step = step
        self.iters = iters
        self.max_iters = max_iters
        self.closed = closed
        self.title = title
        # Context-sensitive productions take priority over context-free
        # ones; within each group the FIRST match wins.  Both rules are
        # stated in the 2003 course notes and in L-Py.
        self._ordered = ([p for p in self.productions if p.contextual] +
                         [p for p in self.productions if not p.contextual])
        self._by_sym = {}
        for p in self._ordered:
            self._by_sym.setdefault(p.strict_sym, []).append(p)

    # -- parsing ------------------------------------------------------

    @classmethod
    def parse(cls, text, params=None):
        """Parse the text syntax.  Raises GrammarError with a reason.

        `params` overrides the defaults of any `#param` the grammar
        declares -- {name: value}.  Overriding at PARSE time rather than
        at derivation time is deliberate: axiom arguments are folded to
        literals while parsing, so a parameter used in the axiom would
        otherwise be frozen at its declared default.
        """
        overrides = {str(k): float(v) for k, v in (params or {}).items()}
        declared = []
        constants, ignore, names, mode = {}, set(), [], "parallel"
        draw, angle, step = set(), None, None
        iters, max_iters, closed, title = None, None, False, ""
        develop = False
        axiom_src, rule_srcs = None, []

        # Block comments may SPAN LINES, so they are stripped from the
        # whole source before it is split -- doing it per line silently
        # swallowed every line of a multi-line /* ... */ block.
        text_nc = _COMMENT_RE.sub(" ", text)
        for raw in text_nc.splitlines():
            # Comments must not collide with the turtle alphabet.  `--`
            # is "turn right twice" and `//` is "roll right twice", both
            # of which occur in real grammars -- the Koch snowflake's
            # axiom is literally `F--F--F`.  Treating either as an inline
            # comment silently truncates the axiom to `F` and still draws
            # a plausible-looking curve, which is the worst kind of bug.
            # So: `/* ... */` inline (the form the published listings
            # actually use), and `--` or `//` only at the START of a line.
            line = raw.strip()
            if line.startswith("--") or line.startswith("//"):
                continue
            if not line or line.startswith("#!"):
                continue
            low = line.lower()
            if low.startswith("#define"):
                parts = line.split(None, 2)
                if len(parts) < 3:
                    raise GrammarError(f"bad #define: {line!r}")
                try:
                    constants[parts[1]] = float(
                        compile_expr(parts[2], (), constants).ev({}))
                except (ExprError, AttributeError) as exc:
                    raise GrammarError(f"bad #define {parts[1]!r}: {exc}")
                continue
            if low.startswith("#develop"):
                # This grammar describes a FILAMENT, whose single
                # generation is a bare rod; ask the host to draw the
                # developmental series instead.
                develop = True
                continue
            if low.startswith("#param"):
                # #param NAME DEFAULT [MIN MAX] [Label with spaces]
                #
                # A constant the CALLER may override -- the hook the
                # operator uses to turn a grammar's own knobs into
                # sliders.  It behaves exactly like `#define` when no
                # override is supplied, so a grammar stays valid, and
                # self-describing, outside Blender.
                toks = line.split()
                if len(toks) < 3:
                    raise GrammarError(f"bad #param: {line!r}")
                pname = toks[1]
                try:
                    pdef = float(compile_expr(toks[2], (), constants).ev({}))
                except (ExprError, AttributeError) as exc:
                    raise GrammarError(f"bad #param {pname!r}: {exc}")
                choices = None
                grp = _CHOICE_RE.search(line)
                if grp:
                    choices = []
                    for opt in grp.group(1).split("|"):
                        opt = opt.strip()
                        if not opt:
                            continue
                        if "=" in opt:
                            ctext, cval = opt.rsplit("=", 1)
                        else:
                            ctext, cval = opt, opt
                        try:
                            choices.append((ctext.strip(), float(cval)))
                        except ValueError:
                            raise GrammarError(
                                f"bad #param {pname!r}: choice {opt!r} has "
                                f"no numeric value (use `Text=value`)")
                    if not choices:
                        raise GrammarError(
                            f"bad #param {pname!r}: empty choice list")
                    rec = Param(pname, pdef, None, None, 0.0,
                                (line[grp.end():].strip() or pname),
                                pdef, choices)
                    rec.value = rec.snap(overrides.get(pname, pdef))
                    constants[pname] = rec.value
                    declared.append(rec)
                    continue

                rest, lo, hi, pstep = toks[3:], None, None, 0.0
                if len(rest) >= 2 and _isnum(rest[0]) and _isnum(rest[1]):
                    lo, hi = float(rest[0]), float(rest[1])
                    rest = rest[2:]
                    if hi < lo:
                        raise GrammarError(
                            f"bad #param {pname!r}: max {hi} below min {lo}")
                    if rest and _isnum(rest[0]):
                        pstep = abs(float(rest[0]))
                        rest = rest[1:]
                rec = Param(pname, pdef, lo, hi, pstep,
                            " ".join(rest) or pname, pdef)
                rec.value = rec.snap(overrides.get(pname, pdef))
                constants[pname] = rec.value
                declared.append(rec)
                continue
            if low.startswith("#ignore") or low.startswith("#consider"):
                syms = line.split(None, 1)[1] if len(line.split()) > 1 else ""
                # `#consider` is the complement of `#ignore`; store the
                # listed symbols and a flag saying which sense applies.
                if low.startswith("#ignore"):
                    ignore.update(s for s in syms.split() if s)
                else:
                    ignore.add(("__consider__",))
                    ignore.update(("__c__" + s) for s in syms.split() if s)
                continue
            if low.startswith("#draw"):
                draw.update(s for s in line.split(None, 1)[1].split() if s)
                continue
            if low.startswith("#angle"):
                angle = float(line.split(None, 1)[1])
                continue
            if low.startswith("#step"):
                step = float(line.split(None, 1)[1])
                continue
            if low.startswith("#iters"):
                bits = line.split(None, 1)[1].replace(",", " ").split()
                iters = int(float(bits[0]))
                if len(bits) > 1:
                    max_iters = int(float(bits[1]))
                continue
            if low.startswith("#closed"):
                closed = True
                continue
            if low.startswith("#title"):
                title = line.split(None, 1)[1].strip()
                continue
            if low.startswith("#mode"):
                mode = line.split(None, 1)[1].strip().lower()
                if mode not in ("parallel", "sequential"):
                    raise GrammarError(f"unknown #mode {mode!r}")
                continue
            if low.startswith("module"):
                decl = line.split(None, 1)[1]
                for item in _split_args(decl) or [decl]:
                    nm = item.split("(")[0].strip()
                    if nm:
                        names.append(nm)
                continue
            if low.startswith("axiom"):
                axiom_src = line.split(":", 1)[1].strip()
                continue
            if "->" in line or "→" in line:
                rule_srcs.append(line)
                continue
            raise GrammarError(f"unrecognised line: {line!r}")

        if axiom_src is None:
            raise GrammarError("grammar has no `axiom:` line")

        names = tuple(dict.fromkeys(names))
        axiom = [Module(sym, tuple(_lit(a, constants) for a in args))
                 for sym, args in tokenize(axiom_src, names)]
        prods = [_parse_rule(s, names, constants) for s in rule_srcs]
        g = cls(axiom, prods, constants, ignore, names, mode, text,
                draw, angle, step, iters, max_iters, closed, title)
        g.params = tuple(declared)
        g.develop = develop
        return g

    # -- derivation ---------------------------------------------------

    def derive(self, n, seed=None, budget=DEFAULT_BUDGET,
               start=None, start_each=None, end_each=None):
        """Rewrite for `n` steps (parallel) or until quiescent
        (sequential), returning the resulting Word.

        `budget` caps the word length; exceeding it raises GrammarError
        rather than hanging Blender's UI.  `start_each(step, word)` and
        `end_each(step, word)` are the per-step hooks from L-Py; they are
        what make a live module-count read-out or a post-processing pass
        possible without touching this module.
        """
        rng = random.Random(seed if seed is not None else 0)
        word = list(self.axiom if start is None else start)
        sequential = self.mode == "sequential"
        for step in range(int(n)):
            if start_each is not None:
                start_each(step, word)
            nxt = (self._step_sequential(word, rng) if sequential
                   else self._step_parallel(word, rng))
            if len(nxt) > budget:
                raise GrammarError(
                    f"derivation exceeded the {budget:,}-module budget at "
                    f"step {step + 1} (reached {len(nxt):,}); reduce the "
                    f"iteration count")
            changed = nxt != word
            word = nxt
            if end_each is not None:
                end_each(step, word)
            if sequential and not changed:
                break            # quiescent: only terminals remain
        return word

    def _step_parallel(self, word, rng):
        out = []
        for i, mod in enumerate(word):
            p, binding = self._select(word, i, mod, rng)
            if p is None:
                out.append(mod)
            else:
                out.extend(_expand(p, binding))
        return out

    def _step_sequential(self, word, rng):
        """Chomsky-style: rewrite the FIRST matching module only."""
        for i, mod in enumerate(word):
            p, binding = self._select(word, i, mod, rng)
            if p is not None:
                return word[:i] + _expand(p, binding) + word[i + 1:]
        return list(word)

    def _select(self, word, i, mod, rng):
        """Return (production, binding) for the module at `i`, or
        (None, None) when the identity production applies."""
        cands = self._by_sym.get(mod.sym)
        if not cands:
            return None, None
        matches = []
        for p in cands:
            binding = self._match(word, i, mod, p)
            if binding is not None:
                matches.append((p, binding))
                # Deterministic rules resolve to the first match; only
                # gather the rest when weights are actually in play.
                if p.prob >= 1.0 and not any(
                        q.prob < 1.0 for q in cands):
                    break
        if not matches:
            return None, None
        if len(matches) == 1:
            return matches[0]
        total = sum(p.prob for p, _ in matches)
        if total <= 0.0:
            return matches[0]
        r = rng.random() * total
        acc = 0.0
        for p, binding in matches:
            acc += p.prob
            if r <= acc:
                return p, binding
        return matches[-1]

    def _match(self, word, i, mod, p):
        """The three matching conditions from the 2003 course notes:
        the letter agrees, the ARITY agrees, and the condition holds.
        Returns the parameter binding, or None."""
        if len(mod.params) != len(p.formals):
            return None
        binding = dict(self.constants)
        binding.update(zip(p.formals, mod.params))
        if p.left and not self._ctx_left(word, i, p.left):
            return None
        if p.right and not self._ctx_right(word, i, p.right):
            return None
        if p.cond is not None:
            try:
                if p.cond.ev(binding) == 0.0:
                    return None
            except ExprError:
                return None
        return binding

    def _skip(self, sym):
        """True when `sym` is invisible to context matching."""
        if ("__consider__",) in self.ignore:
            return ("__c__" + sym) not in self.ignore
        return sym in self.ignore

    def _ctx_left(self, word, i, pat):
        """Left context: walk back, skipping ignored symbols and whole
        completed branches -- the bracketed string does not preserve
        segment adjacency, so `]`...`[` pairs must be jumped."""
        want = list(pat)[::-1]
        j = i - 1
        depth = 0
        while j >= 0 and want:
            sym = word[j].sym
            if sym == BRANCH_CLOSE:
                depth += 1
            elif sym == BRANCH_OPEN:
                if depth == 0:
                    j -= 1          # leaving our own branch: keep looking
                    continue
                depth -= 1
            elif depth == 0 and not self._skip(sym):
                if sym != want[0]:
                    return False
                want.pop(0)
            j -= 1
        return not want

    def _ctx_right(self, word, i, pat):
        """Right context: a subtree, so a pattern may descend into a
        branch.  Bracket symbols in the pattern are matched literally."""
        want = list(pat)
        j = i + 1
        while j < len(word) and want:
            sym = word[j].sym
            if want[0] in (BRANCH_OPEN, BRANCH_CLOSE):
                if sym == want[0]:
                    want.pop(0)
                elif not self._skip(sym):
                    return False
                j += 1
                continue
            if sym == BRANCH_OPEN:
                # Try inside the branch; if the pattern does not continue
                # there, skip the whole branch and try after it.
                j += 1
                continue
            if sym == BRANCH_CLOSE:
                j += 1
                continue
            if self._skip(sym):
                j += 1
                continue
            if sym != want[0]:
                return False
            want.pop(0)
            j += 1
        return not want

    # -- introspection ------------------------------------------------

    def alphabet(self):
        syms = {mod.sym for mod in self.axiom}
        for p in self.productions:
            syms.add(p.strict_sym)
            syms.update(s for s, _ in p.succ)
        return sorted(syms)

    def is_dol(self):
        """True for a deterministic, context-free, NON-PARAMETRIC system
        -- the only class whose size is predictable in closed form (see
        growth.py) and the only one eligible for the numpy fast path."""
        if any(mod.params for mod in self.axiom):
            return False
        for p in self.productions:
            if p.contextual or p.formals or p.cond is not None:
                return False
            if p.prob < 1.0:
                return False
            if any(args for _, args in p.succ):
                return False
        seen = set()
        for p in self.productions:
            if p.strict_sym in seen:
                return False        # two rules for one symbol: not D0L
            seen.add(p.strict_sym)
        return True

    def __repr__(self):
        return (f"<Grammar {len(self.productions)} productions, "
                f"axiom {word_str(self.axiom)!r}, mode={self.mode}>")


