def _selftest():
    # --- tokeniser: the defect this module exists to fix -------------
    assert [s for s, _ in tokenize("FF")] == ["F", "F"]
    assert [s for s, _ in tokenize("Fseg", ("seg",))] == ["F", "seg"]
    assert [s for s, _ in tokenize("Apex", ("Apex",))] == ["Apex"]
    assert [s for s, _ in tokenize("Apex")] == list("Apex"), \
        "undeclared names must still split per character"
    toks = tokenize("A(1,2)B", ())
    assert toks[0][0] == "A" and toks[0][1] == ["1", "2"]

    # --- the published conformance derivation ------------------------
    # ABOP equation (1.7) / Figure 1.34, also printed as equation (2) in
    # the SIGGRAPH 2003 course notes.
    #
    # The two sources disagree about the final word: ABOP prints
    # `C B(1) A(8,7)`, the course notes `C B(1) B(4) A(1.33,0)`.  ABOP is
    # right.  At step 3 the word is `C B(2) A(4,3)`, so A has y = 3;
    # p1's guard is `y <= 3`, which HOLDS, giving A(x*2, x+y) = A(8,7).
    # Reaching the course notes' word would need p2 (`y > 3`) to fire at
    # y = 3.  Deriving from the rules is the arbiter, and it agrees with
    # ABOP at every step.
    g = Grammar.parse("""
        axiom: B(2)A(4,4)
        p1: A(x,y) : y <= 3 -> A(x*2, x+y)
        p2: A(x,y) : y >  3 -> B(x)A(x/y, 0)
        p3: B(x)   : x <  1 -> C
        p4: B(x)   : x >= 1 -> B(x-1)
    """)
    expected = ["B(2)A(4,4)",
                "B(1)B(4)A(1,0)",
                "B(0)B(3)A(2,1)",
                "CB(2)A(4,3)",
                "CB(1)A(8,7)"]
    for k, want in enumerate(expected):
        got = word_str(g.derive(k))
        assert got == want, f"step {k}: got {got!r}, want {want!r}"

    # --- arity is part of matching -----------------------------------
    g2 = Grammar.parse("""
        axiom: A(1)A(1,1)
        p1: A(x)   -> B
        p2: A(x,y) -> C
    """)
    assert word_str(g2.derive(1)) == "BC"

    # --- context sensitivity, priority and #ignore -------------------
    g3 = Grammar.parse("""
        #ignore + -
        axiom: B+A+A+A
        p1: B < A -> B
        p2: A -> A
    """)
    # the signal advances one internode per step, THROUGH the ignored +
    assert word_str(g3.derive(1)) == "B+B+A+A", word_str(g3.derive(1))
    assert word_str(g3.derive(3)) == "B+B+B+B"

    # a context-sensitive rule outranks a context-free one for the same
    # symbol even when it is listed second
    g4 = Grammar.parse("""
        axiom: XA
        p1: A -> Z
        p2: X < A -> Y
    """)
    assert word_str(g4.derive(1)) == "XY"

    # --- the mesotonic test: what the old engine provably could not do
    # Prusinkiewicz & Kari: subapical branching in a NON-parametric D0L
    # forces a basitonic form.  With a parameter carrying each branch's
    # growth potential, the middle branches end up longest.
    gm = Grammar.parse("""
        axiom: F A(0)
        p1: A(v)          -> [-F B(v)][+F B(v)] F A(v+1)
        p2: B(v) : v > 0  -> F B(v-1)
    """)
    w = gm.derive(8)
    lens, depth, cur = [], 0, 0
    for mod in w:
        if mod.sym == "[":
            depth, cur = depth + 1, 0
        elif mod.sym == "]":
            depth -= 1
            if depth == 0:
                lens.append(cur)
        elif depth and mod.sym == "F":
            cur += 1
    pairs = [max(lens[i], lens[i + 1]) for i in range(0, len(lens) - 1, 2)]
    assert len(pairs) >= 5, f"expected several branch pairs, got {pairs}"
    peak = pairs.index(max(pairs))
    assert 0 < peak < len(pairs) - 1, \
        f"branch lengths {pairs} peak at index {peak}: not mesotonic"

    # --- stochastic rules are reproducible per seed ------------------
    gs = Grammar.parse("""
        axiom: A
        p1: A -> AA : 0.5
        p2: A -> B  : 0.5
    """)
    a = word_str(gs.derive(6, seed=7))
    b = word_str(gs.derive(6, seed=7))
    c = word_str(gs.derive(6, seed=8))
    assert a == b, "same seed must give the same word"
    assert a != c, "different seeds should differ here"

    # --- sequential (Chomsky) mode stops when quiescent ---------------
    gq = Grammar.parse("""
        #mode sequential
        axiom: AA
        p1: A -> b
    """)
    assert word_str(gq.derive(1)) == "bA", "sequential rewrites one module"
    assert word_str(gq.derive(50)) == "bb", "and then goes quiescent"

    # --- the budget refuses rather than hanging ----------------------
    gb = Grammar.parse("axiom: A\np1: A -> AA")
    try:
        gb.derive(40, budget=10_000)
    except GrammarError as exc:
        assert "budget" in str(exc)
    else:
        raise AssertionError("runaway derivation must raise")

    # --- comments must not eat turtle symbols ------------------------
    # Regression: `--` is "turn right twice" and `//` is "roll right
    # twice".  Treating them as inline comments truncated the Koch axiom
    # to `F` and its successor to `F+F`, and the curve still LOOKED
    # plausible -- so this is asserted rather than eyeballed.
    gk = Grammar.parse("""
        axiom: F--F--F
        p1: F -> F+F--F+F   /* the Koch generator */
    """)
    assert word_str(gk.axiom) == "F--F--F", word_str(gk.axiom)
    assert "".join(s for s, _ in gk.productions[0].succ) == "F+F--F+F"
    gr = Grammar.parse("""
        axiom: F//F
        p1: F -> F
    """)
    assert word_str(gr.axiom) == "F//F"
    # whole-line comments still work, in both spellings
    g_c = Grammar.parse("""
        -- a comment
        // another
        axiom: F
        p1: F -> FF
    """)
    assert word_str(g_c.axiom) == "F"

    # --- classification ----------------------------------------------
    assert Grammar.parse("axiom: F\np1: F -> F+F").is_dol()
    assert not g.is_dol(), "parametric system is not D0L"
    assert not gs.is_dol(), "stochastic system is not D0L"

    # --- malformed grammars report, not crash ------------------------
    for bad in ("p1: A -> B",                       # no axiom
                "axiom: A\np1: AB -> C",            # two strict predecessors
                "axiom: A\nwhat is this"):
        try:
            Grammar.parse(bad)
        except GrammarError:
            pass
        else:
            raise AssertionError(f"{bad!r} should not parse")

    print("core: OK -- maximal-munch tokeniser, published derivation, "
          "arity+context+priority matching, mesotonic parametric case, "
          "seeded stochastic, sequential mode, budget")
