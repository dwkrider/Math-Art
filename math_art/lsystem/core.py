
# The rewriting engine: modules, a maximal-munch tokeniser, productions,
# and derivation.
#
# THE POINT OF THIS MODULE.  The generator this replaces rewrote with
#
#     "".join(rules.get(c, c) for c in s)
#
# -- a per-CHARACTER substitution.  That makes multi-character module
# names (`Fl`, `internode`, `seg`, `Apex`) not merely unsupported but
# *unrepresentable*, which in turn makes every model in chapters 3-5 of
# "The Algorithmic Beauty of Plants" inexpressible.  The tokeniser below
# is the piece that unblocks them, and parameters follow from it.
#
# There is also a theorem behind the change, not just an aesthetic
# complaint.  Frijters and Lindenmayer observed, and Prusinkiewicz and
# Kari formalised, that arbitrarily large MESOTONIC and ACROTONIC
# structures cannot be generated by non-parametric deterministic
# 0L-systems with subapical branching: because new branches appear only
# near the apices, the lowest branches are created first and have the
# longest to grow, so a BASITONIC (base-heavy) form is forced.  Real
# plants are frequently heaviest in the middle or at the top.  So the old
# engine could not produce a realistically shaped tree at all, and no
# choice of preset or angle could fix it -- parameters are the documented
# escape.  `_selftest` checks exactly that case.
#
# WHAT A GRAMMAR LOOKS LIKE.  The text syntax transcribes the book's
# listings closely:
#
#     #define R 0.9              -- a constant, usable in any expression
#     #param  R 0.9 0.5 1.0 0.01 Contraction ratio
#                                -- the same, but declared FREE: a host UI
#                                   can render it, within the range and to
#                                   the increment the author chose
#     #param  arity 2 (Binary=2|Ternary=3) Branches per node
#                                -- a free parameter restricted to a fixed
#                                   set of choices, rendered as a menu
#     #ignore + - /              -- skipped when matching context
#     #mode parallel             -- or `sequential` (see below)
#     module Apex(age), Seg(len) -- declare multi-character module names
#     axiom: Apex(0)
#     p1: Apex(a) : a < 5 -> Seg(1)[+Apex(a+1)]Apex(a+1)
#     p2: A(x) < B(y) > C(z) : x+z > 10 -> E((x+y)/2)F((y+z)/2)
#     p3: A -> B : 0.4           -- stochastic weight after the successor
#
# PARALLEL vs SEQUENTIAL.  L-system productions describe development in
# TIME and are applied to every module at once; Chomsky-style
# decomposition rules describe structure in SPACE and may be applied one
# at a time, terminating when no rule matches rather than after a fixed
# step count.  Both are supported because the curve work and the organ
# placement work in this project are structural, not developmental.
#
# References:
# - Aristid Lindenmayer, "Mathematical models for cellular interaction in
#   development", J. Theoretical Biology 18, 1968.
# - Przemyslaw Prusinkiewicz and Aristid Lindenmayer, "The Algorithmic
#   Beauty of Plants", Springer, 1990 -- sections 1.2 (the triple
#   <V, omega, P>), 1.7 (stochastic), 1.8 (context-sensitive, #ignore)
#   and 1.10 (parametric modules, conditions, #define).
# - Przemyslaw Prusinkiewicz, Jim Hanan, Mark Hammel and Radomir Mech,
#   "L-systems: from the Theory to Visual Models of Plants", SIGGRAPH
#   2003 course notes, chapter 2-1, section 4 -- the three matching
#   conditions (letter, arity, condition) implemented in `_match`.
# - Frederic Boudon, Christophe Pradal, Thomas Cokelaer, Przemyslaw
#   Prusinkiewicz and Christophe Godin, "L-Py: an L-system simulation
#   framework ... based on a dynamic language", Frontiers in Plant
#   Science 3:76, 2012 -- declaration-driven tokenisation, matching on
#   name AND arity, and the StartEach/EndEach hooks.
# - Przemyslaw Prusinkiewicz, Lars Mundermann, Radoslaw Karwowski and
#   Brendan Lane, "The use of positional information in the modeling of
#   plants", SIGGRAPH 2001 -- the L-system versus Chomsky-grammar
#   distinction that `mode` implements.
# - Przemyslaw Prusinkiewicz and Lila Kari, "Subapical bracketed
#   L-systems" -- the mesotonic/acrotonic impossibility result.

import random
import re
from collections import namedtuple

from .expr import ExprError, compile_expr

# A module is a letter plus zero or more real parameters: `F(1.0, 0.5)`.
Module = namedtuple("Module", "sym params")

# A word is a list of Modules.  Brackets are ordinary modules with the
# symbols '[' and ']' so that context matching can skip over them.
BRANCH_OPEN, BRANCH_CLOSE = "[", "]"

DEFAULT_BUDGET = 2_000_000


class GrammarError(ValueError):
    """A grammar could not be parsed.  Carries a human-readable reason;
    the operator surfaces it with self.report({'ERROR'}) instead of
    raising into Blender's UI."""


def m(sym, *params):
    """Terse Module constructor for hand-written data tables."""
    return Module(sym, tuple(float(p) for p in params))


def word_str(word):
    """Render a word the way the books print it, so derivations can be
    compared against published sequences character by character."""
    out = []
    for mod in word:
        if mod.params:
            args = ",".join(_fmt(p) for p in mod.params)
            out.append(f"{mod.sym}({args})")
        else:
            out.append(mod.sym)
    return "".join(out)


def _fmt(v):
    if v == int(v):
        return str(int(v))
    return f"{round(v, 6):g}"


# ---------------------------------------------------------------------
# Tokenising
# ---------------------------------------------------------------------

def tokenize(src, names=()):
    """Split `src` into Modules by MAXIMAL MUNCH over declared names.

    Declared multi-character names are tried longest-first; anything else
    is a single character.  So with `Apex` declared, `Apex` is one module
    -- but `FF` is still two, and `Fseg` is `F` then `seg` (given `seg`
    declared).  Without this rule `Apex` would tokenise as A, p, e, x,
    which is precisely the defect being fixed.

    Parameters are parsed as raw expression SOURCE here; the caller
    decides whether they are literals (in an axiom) or expressions (in a
    successor).
    """
    ordered = sorted({n for n in names if n}, key=len, reverse=True)
    out = []
    i, n = 0, len(src)
    while i < n:
        c = src[i]
        if c.isspace():
            i += 1
            continue
        sym = None
        for cand in ordered:
            if src.startswith(cand, i):
                # A declared name must not be a prefix of a longer
                # identifier: with `seg` declared, `segment` is not `seg`
                # followed by `ment` unless `ment` is declared too.
                j = i + len(cand)
                if not (cand[-1].isalnum() and j < n and
                        (src[j].isalnum() or src[j] == "_")
                        and not any(src.startswith(o, j) for o in ordered)):
                    sym = cand
                    break
        if sym is None:
            sym = c
        i += len(sym)
        args = []
        if i < n and src[i] == "(":
            depth, j = 0, i
            while j < n:
                if src[j] == "(":
                    depth += 1
                elif src[j] == ")":
                    depth -= 1
                    if depth == 0:
                        break
                j += 1
            if depth != 0:
                raise GrammarError(f"unbalanced '(' after {sym!r} in {src!r}")
            args = _split_args(src[i + 1:j])
            i = j + 1
        out.append((sym, args))
    return out


def _split_args(s):
    """Split `a, b(c,d), e` on top-level commas only."""
    out, depth, cur = [], 0, []
    for ch in s:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    tail = "".join(cur).strip()
    if tail or out:
        out.append(tail)
    return [a for a in out if a != ""] or ([] if not out else out)


