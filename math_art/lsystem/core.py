_LABEL_RE = re.compile(r"^[A-Za-z_]\w*$")
_COMMENT_RE = re.compile(r"/\*.*?\*/", re.S)
#: the `(a|b=2|c)` group of a `#param` choice declaration
_CHOICE_RE = re.compile(r"\(([^)]*)\)")


def _lit(src, constants):
    e = compile_expr(src, (), constants)
    if e is None:
        return 0.0
    return e.ev({})


def _looks_like_label(s, names):
    """A leading `p1:` is a rule label, not a predecessor.

    The ambiguity is real -- `A : x>1 -> B` has a predecessor before the
    colon, while `p1: A -> B` has a label.  Rule: a label is a bare
    identifier that is NOT a declared module name and either contains a
    digit or is longer than one character.  That accepts `p1`, `rule2`
    and `grow`, and rejects the single-letter module names the books use.
    """
    s = s.strip()
    if not _LABEL_RE.match(s) or s in names:
        return False
    return len(s) > 1 or any(ch.isdigit() for ch in s)


def _parse_rule(src, names, constants):
    arrow = "->" if "->" in src else "→"
    lhs, rhs = src.split(arrow, 1)

    # successor : probability
    prob = 1.0
    if ":" in rhs:
        head, tail = rhs.rsplit(":", 1)
        try:
            prob = float(compile_expr(tail, (), constants).ev({}))
            rhs = head
        except (ExprError, AttributeError, TypeError):
            pass                        # the ':' belonged to the successor

    parts = lhs.split(":")
    label, cond_src = None, None
    if len(parts) >= 3:
        label, pred_src, cond_src = parts[0], parts[1], ":".join(parts[2:])
    elif len(parts) == 2:
        if _looks_like_label(parts[0], names):
            label, pred_src = parts[0], parts[1]
        else:
            pred_src, cond_src = parts[0], parts[1]
    else:
        pred_src = parts[0]

    left, strict, right = _split_context(pred_src)
    stoks = tokenize(strict, names)
    if len(stoks) != 1:
        raise GrammarError(
            f"a production needs exactly one strict predecessor, got "
            f"{len(stoks)} in {src!r}")
    sym, formals = stoks[0]
    for f in formals:
        if not _LABEL_RE.match(f.strip()):
            raise GrammarError(
                f"formal parameter {f!r} is not a name in {src!r}")
    formals = tuple(f.strip() for f in formals)

    cond = compile_expr(cond_src, formals, constants) if cond_src else None
    succ = []
    for s, args in tokenize(rhs, names):
        succ.append((s, [compile_expr(a, formals, constants) for a in args]))

    return Production(label,
                      [s for s, _ in tokenize(left, names)] if left else [],
                      sym, formals,
                      [s for s, _ in tokenize(right, names)] if right else [],
                      cond, succ, prob, src.strip())


def _split_context(pred):
    """`a < B > c` -> ('a', 'B', 'c').  The '<' and '>' that separate
    context are unambiguous here because a predecessor never contains a
    relational operator (those live in the condition)."""
    left, rest = ("", pred)
    if "<" in pred:
        left, rest = pred.split("<", 1)
    right = ""
    if ">" in rest:
        rest, right = rest.split(">", 1)
    return left.strip(), rest.strip(), right.strip()


def _expand(p, binding):
    out = []
    for sym, args in p.succ:
        if args:
            vals = []
            for a in args:
                try:
                    vals.append(a.ev(binding) if a is not None else 0.0)
                except ExprError:
                    vals.append(0.0)
            out.append(Module(sym, tuple(vals)))
        else:
            out.append(Module(sym, ()))
    return out


def parse(text, params=None):
    """Convenience wrapper: `core.parse(text)` -> Grammar.

    `params` overrides any `#param` the grammar declares.
    """
    return Grammar.parse(text, params)


