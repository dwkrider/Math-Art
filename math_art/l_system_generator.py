def _preset_items():
    """Enum rows grouped as Curves / Plants / Trees."""
    items = []
    for group, keys in ls.GROUPS:
        for k in sorted(keys):
            items.append((k, f"{ls.title(k)}", f"{group}: {ls.title(k)}"))
    return items


