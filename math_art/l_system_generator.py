
# L-system Generator for Blender -- a thin front-end over `lsystem/`.
#
# Lindenmayer systems: a short axiom is rewritten by parallel
# string-substitution rules for a number of generations, then read as
# turtle commands -- draw forward, turn, pitch, roll, push/pop for
# branching -- and emitted as bevelled curves, filled blades, or a
# skeleton mesh.
#
# WHAT CHANGED, AND WHY IT MATTERS.  This module used to BE the engine,
# and it rewrote with `"".join(rules.get(c, c) for c in s)` -- a
# per-character substitution.  That made it a D0L-system: deterministic,
# context-free, non-parametric, single-character alphabet, one global
# angle, one global step, 11 of the 20 Appendix-C turtle symbols, and a
# single bevelled curve of uniform width and no colour.
#
# The limitation was not a shortage of presets.  Multi-character module
# names (`Fl`, `internode`, `seg`, `plant`) were UNREPRESENTABLE, so
# every model in chapters 3-5 of "The Algorithmic Beauty of Plants" was
# out of reach.  And there is a theorem: Prusinkiewicz and Kari showed
# that arbitrarily large mesotonic and acrotonic structures cannot be
# generated by non-parametric deterministic 0L-systems with subapical
# branching -- so the old engine could not make a realistically shaped
# tree at all, whatever angles you chose.
#
# The engine now lives in the `lsystem` subpackage (parametric,
# stochastic, context-sensitive, full turtle, growth prediction), the
# same way the Seifert surface engine lives in `seifert`.  This file
# keeps only the operator, its properties and the preset enum -- and
# keeps its `bl_idname` and the original seven preset keys, so saved
# operator presets and muscle memory both survive.
#
# References:
# - Aristid Lindenmayer, "Mathematical models for cellular interactions
#   in development", J. Theoretical Biology 18, 1968.
# - Przemyslaw Prusinkiewicz and Aristid Lindenmayer, "The Algorithmic
#   Beauty of Plants", Springer, 1990 (turtle interpretation, most of
#   these production rules, and Appendix C's symbol table).
# - Przemyslaw Prusinkiewicz, Jim Hanan, Mark Hammel and Radomir Mech,
#   "L-systems: from the Theory to Visual Models of Plants", SIGGRAPH
#   2003 course notes, chapter 2-1.
# - Grzegorz Rozenberg and Arto Salomaa, "The Mathematical Theory of
#   L Systems", Academic Press, 1980 (growth functions).
# - Gosper curve / flowsnake: Martin Gardner, "Mathematical Games",
#   Scientific American 235(6), 1976 (after William Gosper).
#
# Space-filling curve note: `space_curve_generator.py` covers Hilbert,
# Moore and Gilbert with exact index algorithms and remains the better
# route to those.  It does NOT cover Peano, which is why PEANO ships
# here as a substitution curve.

