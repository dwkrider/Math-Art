def _selftest():
    ok = True

    def chk(name, cond, extra=""):
        nonlocal ok
        ok = ok and bool(cond)
        print("  %-52s %s %s" % (name, "OK" if cond else "BAD", extra))

    print("spidron_math: planar construction")
    chk("arm ratio m=6 == 1/sqrt(3)", abs(arm_ratio(6) - 1.0 / SQRT3) < 1e-15,
        "%.12f" % arm_ratio(6))
    chk("arm turn m=6 == 30 deg", abs(degrees(arm_turn(6)) - 30.0) < 1e-12)
    chk("ratio positive only for m >= 5",
        arm_ratio(5) > 0 and arm_ratio(4) <= 1e-15 and arm_ratio(3) < 0)

    # the m=6 ring is the classical isosceles+equilateral pair
    P, Q = planar_rings(6, 1, 1.0, 0.0)[0]
    tris = ring_triangles(P, Q)
    iso = np.array(sorted(hypot(*(np.array(tris[0][0][i]) -
                                  np.array(tris[0][0][(i + 1) % 3])))
                          for i in range(3)))
    equ = np.array(sorted(hypot(*(np.array(tris[1][0][i]) -
                                  np.array(tris[1][0][(i + 1) % 3])))
                          for i in range(3)))
    chk("m=6 ring: 120-deg isosceles (1, 1/r3, 1/r3)",
        np.abs(iso - sorted([1.0, 1 / SQRT3, 1 / SQRT3])).max() < 1e-12)
    chk("m=6 ring: equilateral (1/r3)^3",
        np.abs(equ - 1 / SQRT3).max() < 1e-12)

    # area: the ring triangles exactly tile the annulus between the m-gons
    for m in (5, 6, 8, 12):
        P, Q = planar_rings(m, 1, 1.0, 0.0)[0]

        def area(poly):
            a = 0.0
            for i in range(len(poly)):
                x0, y0 = poly[i]
                x1, y1 = poly[(i + 1) % len(poly)]
                a += x0 * y1 - x1 * y0
            return abs(a) * 0.5
        tri_area = sum(area(t) for t, _ in ring_triangles(P, Q))
        chk("m=%2d ring triangles tile the annulus" % m,
            abs(tri_area - (area(P) - area(Q))) < 1e-12)

    print("spidron_math: the Spidron Formula")
    worst = 0.0
    for beta in np.linspace(0.0, BETA_MAX - 1e-9, 600):
        v = [fold_inner(beta), fold_inner_kiss(beta),
             fold_inner_hujter(beta), fold_inner_cheap(beta)]
        worst = max(worst, max(v) - min(v))
    chk("four independent forms agree", worst < 1e-11, "spread %.2e" % worst)
    chk("a(0+) -> 30 deg", abs(degrees(fold_turn(1e-9)) - 30.0) < 1e-6)
    # Kiss's gamma and Szilassi's a measure the same azimuth advance in
    # frames that differ by a constant; pinning that constant validates
    # gamma, which nothing else exercises.
    off = [degrees(ring_twist(b)) + degrees(fold_turn(b))
           for b in np.linspace(0.05, BETA_PHYSICAL, 200)]
    chk("Kiss gamma = 210 deg - Szilassi a(beta)",
        max(abs(o - 210.0) for o in off) < 1e-9,
        "offset %.9f deg" % off[0])
    chk("a(60) == 60 deg",
        abs(degrees(fold_turn(BETA_PHYSICAL)) - 60.0) < 1e-9)
    chk("b(60) == 30 deg",
        abs(degrees(fold_inner(BETA_PHYSICAL)) - 30.0) < 1e-9)
    chk("b(beta) <= arcsin(1/sqrt3)",
        max(fold_inner(b) for b in np.linspace(0, BETA_MAX, 4000))
        <= BETA_IMAGE_MAX + 1e-12)
    chk("both domain endpoints map to 0",
        fold_inner(0.0) < 1e-12 and fold_inner(BETA_MAX) < 1e-6)
    chk("b(f) < f strictly on (0, 60]",
        all(fold_inner(b) < b
            for b in np.linspace(1e-3, BETA_PHYSICAL, 500)))
    # b(f) = f - f^3/4 + O(f^5); the cubic coefficient is what makes the
    # decay slow (b'(0) = 1), so pin it rather than the naive "small
    # after N steps" test, which is false here -- see the asymptotic
    # check below and Szilassi's Universe-to-quark remark.
    cub = [(f - fold_inner(f)) / f ** 3 for f in (1e-2, 3e-2, 1e-1)]
    chk("b(f) = f - f^3/4 + O(f^5)",
        max(abs(c - 0.25) for c in cub) < 2e-3, "coeff ~ %.6f" % cub[0])
    seq, b = [], BETA_PHYSICAL
    for _ in range(20000):
        b = fold_inner(b)
        seq.append(b)
    chk("iterating decays monotonically",
        all(seq[i + 1] < seq[i] for i in range(len(seq) - 1))
        and seq[-1] > 0.0)
    # x_{k+1} = x_k - x_k^3/4 gives x_k -> sqrt(2/k).
    chk("decay follows beta_k -> sqrt(2)/sqrt(k)",
        abs(seq[19999] * sqrt(20000) - sqrt(2.0)) < 2e-2,
        "beta_k*sqrt(k) = %.4f vs sqrt2 = %.4f"
        % (seq[19999] * sqrt(20000), sqrt(2.0)))

    print("spidron_math: the folded nest")
    for fd in (0.0, 10.0, 30.0, 45.0, 59.0):
        f = radians(fd)
        st = nest_states(f, 6)
        bad_e = bad_i = bad_q = 0.0
        for i in range(len(st) - 1):
            d, a, b = st[i]
            d2, a2, b2 = st[i + 1]
            H, G = skew_hexagon(d, a, b), skew_hexagon(d2, a2, b2)
            H = np.array(H)
            G = np.array(G)
            for k in range(6):
                k1 = (k + 1) % 6
                bad_e = max(bad_e, abs(np.linalg.norm(H[k1] - H[k]) - d))
                t1 = sorted([np.linalg.norm(H[k1] - H[k]),
                             np.linalg.norm(G[k] - H[k]),
                             np.linalg.norm(G[k] - H[k1])])
                t2 = sorted([np.linalg.norm(G[k1] - G[k]),
                             np.linalg.norm(H[k1] - G[k]),
                             np.linalg.norm(H[k1] - G[k1])])
                bad_i = max(bad_i, max(abs(np.array(t1) - sorted(
                    [d, d / SQRT3, d / SQRT3]))))
                bad_q = max(bad_q, max(abs(np.array(t2) - d / SQRT3)))
        chk("f=%4.1f edges keep length d" % fd, bad_e < 1e-12,
            "%.1e" % bad_e)
        chk("f=%4.1f triangles stay congruent" % fd,
            bad_i < 1e-9 and bad_q < 1e-9, "%.1e / %.1e" % (bad_i, bad_q))

    st = nest_states(radians(40.0), 5)
    chk("folded nest is NOT self-similar",
        abs(st[1][2] - st[0][2]) > 1e-3,
        "b0=%.3f b1=%.3f deg" % (degrees(st[0][2]), degrees(st[1][2])))
    st0 = nest_states(0.0, 5)
    chk("flat nest IS self-similar",
        all(abs(s[2]) < 1e-15 for s in st0)
        and abs(st0[1][0] * SQRT3 - st0[0][0]) < 1e-15)
    H = np.array(skew_hexagon(1.0, 0.0, radians(40.0)))
    chk("skew hexagon midpoints lie in the base plane",
        max(abs(0.5 * (H[k][2] + H[(k + 1) % 6][2])) for k in range(6)) < 1e-15)

    V, F, M = nest_mesh(radians(40.0), 6, cap=True)
    edges = {}
    for f in F:
        for i in range(len(f)):
            e = tuple(sorted((f[i], f[(i + 1) % len(f)])))
            edges[e] = edges.get(e, 0) + 1
    inner = sum(1 for c in edges.values() if c == 2)
    chk("capped nest is watertight",
        inner == len(edges) - 6, "%d/%d interior" % (inner, len(edges)))
    Z = np.array(V)
    ext = Z.max(axis=0) - Z.min(axis=0)
    chk("folded nest has real relief (z >= 0.15 x)",
        ext[2] >= 0.15 * ext[0], "z/x = %.3f" % (ext[2] / ext[0]))
    V0, _, _ = nest_mesh(0.0, 6, cap=True)
    Z0 = np.array(V0)
    chk("flat nest is flat", abs(Z0[:, 2]).max() < 1e-15)

    print("spidron_math: spidronise")
    sq = [(1, 0, 0), (0, 1, 0), (-1, 0, 0), (0, -1, 0)]
    V, F, M = spidronise(sq, 0.6, radians(20.0), 5)
    P0 = np.array(V[0])
    rs, ds = [], []
    for i in range(5):
        p = np.array(V[4 * (i + 1)])
        rs.append(np.linalg.norm(p))
        ds.append(atan2(p[1], p[0]))
    ratios = [rs[i + 1] / rs[i] for i in range(len(rs) - 1)]
    chk("images lie on a logarithmic spiral",
        max(abs(r - 0.6) for r in ratios) < 1e-12,
        "ratio %.9f" % ratios[0])
    Va, _, _ = spidronise(sq, 0.6, radians(20.0), 3, chirality=+1)
    Vb, _, _ = spidronise(sq, 0.6, radians(20.0), 3, chirality=-1)
    chk("chirality flips the spiral sense",
        abs(np.array(Va)[4][1] + np.array(Vb)[4][1]) < 1e-12)
    sk = skew_lift(sq, 0.3)
    zs = [v[2] for v in sk]
    chk("skew lift alternates about the plane",
        abs(sum(zs)) < 1e-12 and all(abs(abs(z) - 0.3) < 1e-12 for z in zs))

    print("spidron_math: generalized square pattern")
    chk("theta clamp at s <= sqrt2/2 is pi/4",
        abs(square_theta_max(0.5) - pi / 4.0) < 1e-15)
    chk("theta clamp shrinks above sqrt2/2",
        square_theta_max(0.9) < pi / 4.0,
        "%.4f deg" % degrees(square_theta_max(0.9)))
    worst_m = worst_s = 0.0
    solved = 0
    for (rd, s_, th) in ((40.0, 0.5, 15.0), (60.0, 0.6, 30.0),
                         (30.0, 0.45, 45.0), (25.0, 0.7, 10.0)):
        got = square_solve_ring(radians(rd), s_, radians(th), 'PRO')
        if got is None:
            continue
        solved += 1
        Q, _ = got
        e = [float(np.linalg.norm(Q[(i + 1) % 4] - Q[i])) for i in range(4)]
        worst_m = max(worst_m, max(abs(x - s_) for x in e))
        worst_s = max(worst_s, max(e) - min(e))
    chk("square ring meets the metric constraint (4 cases)",
        solved == 4 and worst_m < 1e-7,
        "|e|-s <= %.1e" % worst_m)
    chk("isotropic ansatz: all four inner edges equal",
        worst_s < 1e-12, "spread %.1e" % worst_s)
    lp, rh = square_nest(radians(50.0), 0.55, radians(20.0), 6, 'PRO')
    chk("square nest chains rings", len(lp) >= 4,
        "%d loops" % len(lp))
    ok_edge = True
    for L in lp[1:]:
        e = [float(np.linalg.norm(L[(i + 1) % 4] - L[i])) for i in range(4)]
        ok_edge = ok_edge and (max(e) - min(e)) < 1e-9
    chk("placed rings stay square", ok_edge)
    lp2, _ = square_nest(radians(50.0), 0.55, radians(20.0), 6, 'ANTI')
    chk("PRO and ANTI are different modes",
        len(lp2) < 2 or abs(float(np.asarray(lp[1])[0][2])
                            - float(np.asarray(lp2[1])[0][2])) > 1e-6)

    print("RESULT:", "OK" if ok else "BAD")
    return ok
