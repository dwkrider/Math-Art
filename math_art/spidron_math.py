# 5.  The generalized square pattern (Imada-Hull-Ku-Tachi)
# --------------------------------------------------------------------

def square_theta_max(s):
    """Largest twist that keeps the square crease pattern free of
    self-intersection (paper Eq. 1)."""
    if s <= sqrt(2.0) / 2.0:
        return pi / 4.0
    return acos(_clamp((1.0 + sqrt(max(2.0 * s * s - 1.0, 0.0))) / (2.0 * s)))


def square_crease_lengths(s, theta):
    """(r1, r2) for a unit outer edge (paper Eq. 2 at t = 0)."""
    r1 = sqrt(max(0.5 * s * s - s * cos(theta) + 0.5, 0.0))
    r2 = sqrt(max(0.5 * s * s - s * sin(theta) + 0.5, 0.0))
    return r1, r2


def _square_outer(rho):
    """The four outer-boundary vertices of a ring at isotropic dihedral
    `rho` (paper Eq. 3 with rho1 = -rho2 = rho), unit edge."""
    t = tan(0.5 * rho)
    # Eq. 3 with rho1 = -rho2 = rho collapses to d = 1/sqrt(2 + t^2);
    # at rho = 0 that is 1/sqrt(2), the flat unit square.
    d = 1.0 / sqrt(2.0 + t * t)
    h = sqrt(max(1.0 - 2.0 * d * d, 0.0))
    sg = 1.0 if rho >= 0 else -1.0
    return np.array([
        [d, 0.0, -sg * 0.5 * h],
        [0.0, d, +sg * 0.5 * h],
        [-d, 0.0, -sg * 0.5 * h],
        [0.0, -d, +sg * 0.5 * h],
    ])


def _circle_about_edge(p0, p1, r1, r2, ref):
    """Parameterise the points at distance r1 from p0 and r2 from p1 as
    a circle; returns (centre, u, v, radius) so the point at angle t is
    centre + radius*(cos t * u + sin t * v).

    `ref` fixes the frame: u points from the circle's centre away from
    `ref` (the ring's own centre), perpendicular to the edge.  Deriving
    the frame from the ring rather than from an arbitrary world axis is
    what makes "the same t on all four edges" mean the same geometric
    configuration -- i.e. what makes the isotropic ansatz valid.
    """
    d = p1 - p0
    L = np.linalg.norm(d)
    e = d / L
    x = (L * L + r1 * r1 - r2 * r2) / (2.0 * L)
    rad2 = r1 * r1 - x * x
    if rad2 <= 0.0:
        return None
    cen = p0 + x * e
    out = cen - np.asarray(ref, float)
    out = out - float(out @ e) * e
    n = np.linalg.norm(out)
    if n < 1e-12:
        tmp = np.array([0.0, 0.0, 1.0])
        if abs(float(e @ tmp)) > 0.9:
            tmp = np.array([1.0, 0.0, 0.0])
        out = np.cross(e, tmp)
        n = np.linalg.norm(out)
    u = out / n
    v = np.cross(e, u)
    return cen, u, v, sqrt(rad2)


def square_solve_ring(rho, s, theta, mode='PRO'):
    """Solve one ring of the generalized square spidron.

    Rather than transcribing the paper's quartic, the inner vertices are
    found from first principles: q_i must sit at r1 from p_i and r2 from
    p_(i+1), which puts it on a circle about that edge; the remaining
    freedom is one angle, fixed by requiring the inner edge |q1 - q0| to
    equal s.  The two real roots of that scalar equation are the paper's
    pro- and anti-rotation modes.  Returns (Q, rho_in) or None.
    """
    P = _square_outer(rho)
    r1, r2 = square_crease_lengths(s, theta)
    # THE FLAT STATE IS A TANGENT ROOT.  At rho = 0 the ring is planar
    # and the metric residual touches zero without changing sign, so the
    # sign-change scan below cannot see it -- the solve would return
    # nothing, or succeed only when float noise in the caller's
    # parameters happened to perturb the tangency into a crossing.  The
    # flat state is known in closed form, so return it directly.
    if abs(rho) < 1e-7:
        c, sn = cos(theta), sin(theta)
        Rz = np.array([[c, -sn, 0.0], [sn, c, 0.0], [0.0, 0.0, 1.0]])
        for sg in (1.0, -1.0):
            Rs = Rz if sg > 0 else Rz.T
            Q = (Rs @ P.T).T * s
            if abs(float(np.linalg.norm(Q[0] - P[0])) - r1) < 1e-9:
                return Q, 0.0
        return (Rz @ P.T).T * s, 0.0
    ctr = P.mean(axis=0)
    circles = []
    for i in range(4):
        c = _circle_about_edge(P[i], P[(i + 1) % 4], r1, r2, ctr)
        if c is None:
            return None
        circles.append(c)

    def q_at(i, t):
        # ISOTROPIC ANSATZ.  The paper's isotropic folded state is
        # phi^1 = -phi^2, so the parameter alternates in sign from edge
        # to edge -- the pattern's 4-fold symmetry is a quarter turn
        # composed with the boundary's z-alternation, not a pure
        # rotation.  With the sign alternating, all four inner edges
        # come out equal identically; with a single shared t they do
        # not, and no configuration satisfies the metric constraint.
        cen, u, v, rad = circles[i]
        tt = t if (i % 2 == 0) else -t
        return cen + rad * (cos(tt) * u + sin(tt) * v)

    def resid(t):
        Q = [q_at(i, t) for i in range(4)]
        return float(np.linalg.norm(Q[1] - Q[0]) - s)

    roots = []
    ts = np.linspace(-pi, pi, 721)
    prev_t, prev_r = ts[0], resid(ts[0])
    for t in ts[1:]:
        r = resid(t)
        if prev_r == 0.0 or (prev_r < 0.0) != (r < 0.0):
            a, b = prev_t, t
            for _ in range(60):
                mid = 0.5 * (a + b)
                rm = resid(mid)
                if (resid(a) < 0.0) != (rm < 0.0):
                    b = mid
                else:
                    a = mid
            roots.append(0.5 * (a + b))
        prev_t, prev_r = t, r
    if not roots:
        return None

    def inner_of(t):
        Q = np.array([q_at(i, t) for i in range(4)])
        cen = Q.mean(axis=0)
        rel = Q - cen
        dd = float(np.linalg.norm(rel[0][:2]))
        edge = float(np.linalg.norm(Q[1] - Q[0]))
        if edge < 1e-12:
            return None
        dn = dd / edge
        tt2 = 1.0 / max(dn * dn, 1e-18) - 2.0
        if tt2 < 0.0:
            tt2 = 0.0
        zsign = 1.0 if rel[1][2] >= rel[0][2] else -1.0
        return Q, 2.0 * atan2(sqrt(tt2), 1.0) * zsign

    cands = []
    for t in roots:
        got = inner_of(t)
        if got is None:
            continue
        Q, rin = got
        # sense of the inner boundary's rotation relative to the outer
        turn = atan2(Q[0][1], Q[0][0]) - atan2(P[0][1], P[0][0])
        while turn > pi:
            turn -= 2 * pi
        while turn < -pi:
            turn += 2 * pi
        cands.append((turn, Q, rin))
    if not cands:
        return None
    cands.sort(key=lambda c: c[0])
    pick = cands[-1] if mode == 'PRO' else cands[0]
    return pick[1], pick[2]


def _similarity(A, B):
    """The scale+rotation+translation carrying point set A onto B
    (Kabsch with uniform scale).  Both are (n, 3) and congruent up to
    similarity; used to place each ring's canonical solution into the
    frame the previous ring left behind."""
    A = np.asarray(A, float)
    B = np.asarray(B, float)
    ca, cb = A.mean(axis=0), B.mean(axis=0)
    X, Y = A - ca, B - cb
    U, S, Vt = np.linalg.svd(X.T @ Y)
    d = np.sign(np.linalg.det(Vt.T @ U.T))
    D = np.diag([1.0, 1.0, d])
    R = Vt.T @ D @ U.T
    var = float((X * X).sum())
    scl = float(S[:2].sum() + d * S[2]) / var if var > 1e-18 else 1.0
    return R, scl, cb, ca


def square_nest(rho0, s, theta, rings, mode='PRO'):
    """Iterate `square_solve_ring` inward, composing each ring's
    canonical solution into world space.  PLEATS alternates the two
    modes ring to ring.  Returns (loops, rhos)."""
    loops = [_square_outer(rho0)]
    rhos = [float(rho0)]
    rho = float(rho0)
    for k in range(rings):
        md = mode
        if mode == 'PLEATS':
            md = 'PRO' if (k % 2 == 0) else 'ANTI'
        got = square_solve_ring(rho, s, theta, md)
        if got is None:
            break
        Q, rho_in = got
        # Q solves the ring whose outer boundary is the CANONICAL
        # _square_outer(rho); map that canonical outer onto the loop we
        # actually have, and carry Q along with it.
        R, scl, cb, ca = _similarity(_square_outer(rho), loops[-1])
        loops.append(((Q - ca) @ R.T) * scl + cb)
        rhos.append(rho_in)
        rho = rho_in
    return loops, rhos


def square_mesh(rho0, s, theta, rings, mode='PRO', cap=True):
    """Mesh of the generalized square spidron."""
    loops, rhos = square_nest(rho0, s, theta, rings, mode)
    verts, faces, mats, base = [], [], [], []
    for L in loops:
        base.append(len(verts))
        verts.extend([tuple(float(c) for c in v) for v in L])
    for i in range(len(loops) - 1):
        o, q = base[i], base[i + 1]
        for k in range(4):
            k1 = (k + 1) % 4
            faces.append((o + k, o + k1, q + k))
            mats.append(0)
            faces.append((q + k, o + k1, q + k1))
            mats.append(1)
    if cap and len(loops) > 1:
        ci = len(verts)
        verts.append(tuple(float(c) for c in np.asarray(loops[-1]).mean(axis=0)))
        o = base[-1]
        for k in range(4):
            faces.append((o + k, o + (k + 1) % 4, ci))
            mats.append(2)
    return verts, faces, mats, rhos


