        def execute(self, context):
            # group and family are whatever the panel says. Choosing a
            # preset already wrote them through _on_preset, so forcing
            # them again here would undo any edit the moment the redo
            # panel re-ran -- which is what made a preset a mode.
            #
            # Except on the very first run. Blender does not call an
            # update callback for a property's DEFAULT, so a fresh Add
            # never fired _on_preset and the default preset was laid
            # into whatever family the family enum defaulted to --
            # Frabjous, a 30-plane part, arriving in the 60-plane
            # family until you switched preset away and back. So sync
            # here too, but only while the user has not touched
            # anything: once they have, user_edited is set, the preset
            # has already dropped to Custom, and this does nothing.
            if self.preset in PRESETS and not self.user_edited:
                g, f, _mb = PRESETS[self.preset]
                self.syncing = True
                self.group, self.family = g, f
                self.syncing = False
                self.base_motif = self.preset
            key = (self.preset if self.preset in PRESETS
                   else self.base_motif)
            motif_builder = (PRESETS[key][2] if key in PRESETS
                             else demo_motif)
            kind, family = self.group, self.family
            if (kind, family) not in _AXES:
                family = 'P3'
                self.report({'WARNING'},
                            "Plane family not available for this "
                            "group -- using 3-fold planes")
            rots = group_rotations(kind)
            a, normals = plane_normals(kind, family)
            u, v = _frame(a)
            d = self.distance
            # how many rotations hold the representative plane -- the
            # in-plane symmetry a motif may be drawn a sector of.
            # Taken before the dedupe below, which is free to thin the
            # rotation list right down to one per plane.
            fold = len(rots) // len(normals)

            motif = None
            if self.motif_object:
                ao = bpy.data.objects.get(self.motif_object)
                if ao is not None and ao.type == 'MESH':
                    motif = ao
                else:
                    self.report({'WARNING'},
                                f"'{self.motif_object}' is not a mesh "
                                f"object -- built the preset motif "
                                f"instead")
            if motif is None:
                verts, faces = motif_builder(d)
                me = bpy.data.meshes.new("SymSculpt Motif")
                me.from_pydata(verts, [], faces)
                me.validate()
                me.update()
                motif = bpy.data.objects.new("SymSculpt Motif", me)
                context.collection.objects.link(motif)
            # the motif is authored and edited flat on the world
            # XY plane; the node group maps it onto the
            # representative plane with this rotation + offset
            plane_rot = Matrix((
                (u[0], v[0], a[0]),
                (u[1], v[1], a[1]),
                (u[2], v[2], a[2]))).to_euler()
            plane_off = (d * a[0], d * a[1], d * a[2])
            motif.matrix_world = Matrix.Identity(4)
            if not motif.data.materials:
                motif.data.materials.append(_motif_material())
            # how high the sculpture has to go to clear the motif --
            # measured from the motif that is actually being used, so
            # a big motif gets a proportionally bigger lift
            lift_z = lift_height([tuple(v.co) for v in
                                  motif.data.vertices],
                                 d, abs(self.shell))

            # Guides have to reach at least as far as the motif they
            # are drawn for, or its outer corners have no lines to sit
            # on.  A motif can run well past the default -- the
            # stellated star's points reach 2*phi^2 -- so widen the
            # disc to cover whatever motif is actually in use.
            r_motif = max((sqrt(v.co[0] ** 2 + v.co[1] ** 2)
                           for v in motif.data.vertices), default=0.0)
            extent = max(self.guide_extent, 1.05 * r_motif / d)
            if extent > self.guide_extent + 1e-9:
                self.report(
                    {'INFO'},
                    f"Motif reaches {r_motif / d:.2f}x the plane "
                    f"distance, so the guides were widened from "
                    f"{self.guide_extent:.2f} to {extent:.2f}")

            # guide pattern (stellation diagram) in the same plane
            segs = stellation_lines(kind, family, d, extent,
                                    self.guide_rings)
            gverts = []
            gedges = []
            for (p0, p1) in segs:
                gverts.append((p0[0], p0[1], 0.0))
                gverts.append((p1[0], p1[1], 0.0))
                gedges.append((len(gverts) - 2, len(gverts) - 1))
            gme = bpy.data.meshes.new("SymSculpt Guides")
            gme.from_pydata(gverts, gedges, [])
            gme.update()
            guides = bpy.data.objects.new("SymSculpt Guides", gme)
            context.collection.objects.link(guides)
            guides.matrix_world = Matrix.Identity(4)
            guides.display_type = 'WIRE'
            guides.hide_render = True

            # Crossing markers. Where k guide lines cross, k+1 planes
            # of the family meet and k+1 parts converge, so these are
            # the points a corner has to land on for the joint to
            # close. Two-plane crossings are left unmarked: every pair
            # of lines makes one and they are everywhere, which is
            # noise rather than information.
            #
            # The marker is an (k+1)-gon -- a triangle at a 3-plane
            # point, a pentagon at a 5-plane one -- because the count
            # IS the thing you are looking for, and reading it off the
            # shape beats counting lines by eye in a stellation
            # pattern dense enough to be worth drawing at all. Each
            # marker also carries a loose vertex dead on the crossing,
            # so vertex snapping puts a motif corner exactly there.
            if self.show_crossings:
                cross = crossing_points(kind, family, d, extent,
                                        self.guide_rings)
                nparts = crossing_parts(kind, family, cross, d)
                cverts = []
                cedges = []
                cfaces = []
                corders = []
                for (cx, cy, _k), planes in zip(cross, nparts):
                    if planes < max(3, self.crossing_min_planes):
                        continue
                    # Size climbs steeply with order so a hub
                    # reads from across the viewport.
                    rad = 0.030 * d * (planes - 2) ** 0.85
                    base = len(cverts)
                    cverts.append((cx, cy, 0.0))       # snap target
                    for t in range(planes):
                        ang = 2.0 * pi * t / planes + pi / 2.0
                        cverts.append((cx + rad * cos(ang),
                                       cy + rad * sin(ang), 0.0))
                    for t in range(planes):
                        cedges.append((base + 1 + t,
                                       base + 1 + (t + 1) % planes))
                    cfaces.append([base + 1 + t for t in range(planes)])
                    corders.append(planes)
                cme = bpy.data.meshes.new("SymSculpt Crossings")
                cme.from_pydata(cverts, cedges, cfaces)
                cme.update()
                _assign_order_materials(cme, corders, False)
                cme.update()
                marks = bpy.data.objects.new("SymSculpt Crossings",
                                             cme)
                context.collection.objects.link(marks)
                marks.matrix_world = Matrix.Identity(4)
                # Filled, and drawn in front rather than nudged up in
                # Z: the markers share the plane with the motif, so
                # they would z-fight it, but lifting them would put
                # the snap vertex off the plane and a corner snapped
                # to it would land out of the plane too.
                marks.display_type = 'SOLID'
                marks.show_in_front = True
                marks.hide_render = True
                n3 = sum(1 for q in nparts if q == 3)
                n5 = sum(1 for q in nparts if q == 5)
                if n3 or n5:
                    self.report({'INFO'},
                                f"{n3} three-plane and {n5} "
                                f"five-plane crossings marked")

            # the sculpture: one point per rotation, euler attribute
            # Drop rotations that would land the motif exactly where
            # another already put it.  A motif carrying the plane's
            # own k-fold symmetry -- as every traced part here does,
            # since each is a whole part rather than a fundamental
            # domain -- is mapped onto itself by k of the rotations.
            # Keeping them stacks k coincident copies of every face:
            # the weld weeds out the duplicate vertices but not the
            # duplicate faces, and Shell then has a k-deep stack to
            # extrude, which collapses into a plain scaling instead
            # of a thickness.
            rots = _distinct_placements(
                rots, [tuple(v.co) for v in motif.data.vertices],
                plane_rot, plane_off)

            pts = bpy.data.meshes.new("SymSculpt")
            pts.from_pydata([(0.0, 0.0, 0.0)] * len(rots), [], [])
            attr = pts.attributes.new("sym_rot", 'FLOAT_VECTOR',
                                      'POINT')
            eulers = []
            for R in rots:
                eulers.extend(Matrix(R).to_euler())
            attr.data.foreach_set('vector', eulers)
            attr = pts.attributes.new("copy_index", 'INT', 'POINT')
            attr.data.foreach_set('value', list(range(len(rots))))
            attr = pts.attributes.new("is_motif", 'BOOLEAN', 'POINT')
            attr.data.foreach_set(
                'value',
                [all(abs(R[i][j] - (1.0 if i == j else 0.0)) < 1e-9
                     for i in range(3) for j in range(3))
                 for R in rots])
            obj = bpy.data.objects.new("SymSculpt", pts)
            context.collection.objects.link(obj)

            mod = obj.modifiers.new("Symmetric Sculpture", 'NODES')
            ng = _node_group()
            mod.node_group = ng
            lift_socket = None
            for item in ng.interface.items_tree:
                if item.in_out == 'INPUT' and item.name == 'Lift':
                    lift_socket = item.identifier
            for item in ng.interface.items_tree:
                if item.in_out != 'INPUT':
                    continue
                if item.name == 'Motif':
                    mod[item.identifier] = motif
                elif item.name == 'Shell':
                    mod[item.identifier] = self.shell
                elif item.name == 'Lift':
                    # sized from the sculpture the motif actually
                    # makes, not from d alone; still a live modifier
                    # input afterwards
                    mod[item.identifier] = lift_z if self.lift else 0.0
                elif item.name == 'Translucent':
                    mod[item.identifier] = self.translucent
                elif item.name == 'Plane Rotation':
                    mod[item.identifier] = list(plane_rot)
                elif item.name == 'Plane Offset':
                    mod[item.identifier] = list(plane_off)

            motif.parent = obj
            motif.matrix_parent_inverse = Matrix.Identity(4)
            guides.parent = obj
            guides.matrix_parent_inverse = Matrix.Identity(4)

            if self.show_part:
                # Shell is the radial extrusion as a fraction of the
                # distance from the origin, so at the plane it is this
                # thick.  Shell 0 leaves the sculpture flat and there
                # is no solid to machine, so fall back to something
                # cuttable rather than a zero-thickness part.
                p_thick = abs(self.shell) * d
                if p_thick < 1e-4:
                    p_thick = 0.02 * d
                    self.report({'WARNING'},
                                "Shell is 0, so the sculpture has no "
                                "thickness -- the part was built at "
                                "2% of the plane distance instead")
                # The part to machine is the WHOLE part, even when the
                # motif is only one sector of it -- Krull is cut as
                # twelve stars, not sixty arms.  Folding first is a
                # no-op on a motif that is already whole.
                wv, wf = fold_motif(
                    [tuple(v.co) for v in motif.data.vertices],
                    [list(p.vertices) for p in motif.data.polygons],
                    fold)
                mloops = boundary_loops(wv, wf)
                pieces = group_loops(mloops)
                pv2 = []
                pf2 = []
                angles = set()
                for outer, holes in pieces:
                    lv, lf, dh = mitred_part(
                        kind, family, [outer] + holes, d, p_thick)
                    base = len(pv2)
                    pv2.extend(lv)
                    pf2.extend([[base + i for i in f] for f in lf])
                    angles.update(dh)
                if pv2:
                    # centre on the Z axis and drop the whole thing
                    # below the XY plane, clear of the guide diagram,
                    # so it can be picked and exported on its own
                    xs = [p[0] for p in pv2]
                    ys = [p[1] for p in pv2]
                    cx = (min(xs) + max(xs)) / 2
                    cy = (min(ys) + max(ys)) / 2
                    top = max(p[2] for p in pv2)
                    dz = -0.6 * d - top
                    pv2 = [(p[0] - cx, p[1] - cy, p[2] + dz)
                           for p in pv2]
                    pme2 = bpy.data.meshes.new("SymSculpt Part")
                    pme2.from_pydata(pv2, [], pf2)
                    pme2.validate()
                    pme2.update()
                    part = bpy.data.objects.new("SymSculpt Part", pme2)
                    part.data.materials.append(_motif_material())
                    context.collection.objects.link(part)
                    part.matrix_world = Matrix.Identity(4)
                    part.parent = obj
                    part.matrix_parent_inverse = Matrix.Identity(4)
                    self.report(
                        {'INFO'},
                        "Part: %d piece(s), %.4g thick (Shell x "
                        "Distance), mating dihedrals %s deg"
                        % (len(pieces), p_thick,
                           ", ".join(f"{x:.2f}"
                                     for x in sorted(angles))
                           or "none (no edge beds against a "
                              "neighbour)"))
                    # An edge drawn nearly-but-not-quite along a guide
                    # line is treated as free and left square, which
                    # looks like the mitre simply failing.  Say so
                    # rather than let it pass silently.
                    near = []
                    for outer, holes in pieces:
                        near.extend(near_mating_edges(
                            kind, family, [outer] + holes, d))
                    if near:
                        worst = max(x[2] for x in near)
                        self.report(
                            {'WARNING'},
                            "%d edge(s) run close to a guide line but "
                            "miss it by up to %.4g (%.2f%% of the "
                            "plane distance), so they were left "
                            "square instead of mitred -- snap those "
                            "points onto the crossing lines to have "
                            "them bed against the neighbour"
                            % (len(near), worst, 100.0 * worst / d))

            if self.show_polyhedron:
                # the solid whose extended face planes are this
                # family, plus a ball on every vertex and a disc
                # where that vertex lands in the guide diagram
                pv, pf = family_polyhedron(kind, family, d)
                pme = bpy.data.meshes.new("SymSculpt Polyhedron")
                pme.from_pydata(pv, [], pf)
                pme.validate()
                pme.update()
                solid = bpy.data.objects.new("SymSculpt Polyhedron",
                                             pme)
                solid.data.materials.append(_solid_material())
                context.collection.objects.link(solid)
                solid.matrix_world = Matrix.Identity(4)
                solid.hide_render = True
                solid.parent = obj
                solid.matrix_parent_inverse = Matrix.Identity(4)

                # A hollow cone at every point where parts really
                # meet, in place of the balls that used to sit on
                # every guide crossing -- hundreds of them, most on
                # points where nothing converges.
                #
                # N sides for the N parts that converge, and the sides
                # are not decoration: the edges run along the creases
                # where consecutive parts meet, which are the
                # intersection lines of their two planes. So the cone
                # is the spike the finished sculpture actually forms
                # there, pointing the way the real one points, and a
                # motif corner snapped to the apex has the wedge it
                # has to fill drawn around it.
                # Computed here, not borrowed from the crossing
                # markers above: that block is behind its own toggle,
                # and reaching into it left this one raising NameError
                # whenever the markers were switched off.
                _allx = crossing_points(kind, family, d, extent,
                                        self.guide_rings)
                _allq = crossing_parts(kind, family, _allx, d)
                meet = [(c, q) for c, q in zip(_allx, _allq)
                        if q >= max(3, self.crossing_min_planes)]
                kverts, kfaces, korders = [], [], []
                L = 0.30 * d
                for (cx, cy, _k), npl in meet:
                    P = (a[0] * d + cx * u[0] + cy * v[0],
                         a[1] * d + cx * u[1] + cy * v[1],
                         a[2] * d + cx * u[2] + cy * v[2])
                    axis = _normalize(P)
                    # the planes of the family that pass through P
                    thru = [n for n in normals
                            if abs(n[0] * P[0] + n[1] * P[1]
                                   + n[2] * P[2] - d) < 1e-6 * max(1.0, d)]
                    if len(thru) < 3:
                        continue
                    # order them by angle about the axis, so that
                    # "adjacent" means adjacent around the spike
                    e1 = _normalize(_frame(axis)[0])
                    e2 = (axis[1] * e1[2] - axis[2] * e1[1],
                          axis[2] * e1[0] - axis[0] * e1[2],
                          axis[0] * e1[1] - axis[1] * e1[0])
                    def _bearing(n):
                        return math.atan2(n[0] * e2[0] + n[1] * e2[1]
                                          + n[2] * e2[2],
                                          n[0] * e1[0] + n[1] * e1[1]
                                          + n[2] * e1[2])
                    thru = sorted(thru, key=_bearing)
                    dirs = []
                    for i in range(len(thru)):
                        n1 = thru[i]
                        n2 = thru[(i + 1) % len(thru)]
                        e = (n1[1] * n2[2] - n1[2] * n2[1],
                             n1[2] * n2[0] - n1[0] * n2[2],
                             n1[0] * n2[1] - n1[1] * n2[0])
                        if sqrt(sum(c * c for c in e)) < 1e-9:
                            continue
                        e = _normalize(e)
                        # inward: the spike points out, its edges run
                        # back towards the body of the sculpture
                        if (e[0] * axis[0] + e[1] * axis[1]
                                + e[2] * axis[2]) > 0:
                            e = (-e[0], -e[1], -e[2])
                        dirs.append(e)
                    if len(dirs) < 3:
                        continue
                    apex = len(kverts)
                    kverts.append(P)
                    for e in dirs:
                        kverts.append((P[0] + L * e[0], P[1] + L * e[1],
                                       P[2] + L * e[2]))
                    m = len(dirs)
                    for i in range(m):
                        kfaces.append([apex, apex + 1 + i,
                                       apex + 1 + (i + 1) % m])
                        korders.append(npl)
                if kfaces:
                    kme = bpy.data.meshes.new("SymSculpt Spikes")
                    kme.from_pydata(kverts, [], kfaces)
                    kme.validate()
                    kme.update()
                    _assign_order_materials(kme, korders, True)
                    spikes = bpy.data.objects.new("SymSculpt Spikes",
                                                  kme)
                    context.collection.objects.link(spikes)
                    spikes.matrix_world = Matrix.Identity(4)
                    spikes.hide_render = True
                    spikes.parent = obj
                    spikes.matrix_parent_inverse = Matrix.Identity(4)
                    if lift_socket is not None:
                        _drive_z_from_lift(spikes, obj, mod.name,
                                           lift_socket)
                if lift_socket is not None:
                    _drive_z_from_lift(solid, obj, mod.name,
                                       lift_socket)
                self.report(
                    {'INFO'},
                    f"{len(meet)} points where parts meet, "
                    f"{len(kfaces)} spike faces")

            for o in context.selected_objects:
                o.select_set(False)
            obj.select_set(True)
            motif.select_set(True)
            context.view_layer.objects.active = obj
            self.report(
                {'INFO'},
                f"{len(normals)} planes x {fold}-fold: edit the "
                f"Motif object and every copy follows")
            return {'FINISHED'}

