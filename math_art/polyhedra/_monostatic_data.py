# equation: its makers (gomboc.eu) describe it as a "tennis-ball"
# assembly of segments of simple surfaces (cylinder, ellipsoid, cone)
# and planes joined along crease edges.  Here the recognisable shape
# is digitised as the real spherical-harmonic coefficients of its
# SUPPORT function h(u) = max_x x.u about the centre of mass (sparse:
# GOMBOC_SH_IDX are the flat indices l*l+l+m into the (L+1)^2 array,
# GOMBOC_SH_COEF the fully-normalised real coefficients).  The
# generator heat-kernel-smooths these (a convexity-preserving
# Minkowski average) and meshes the strictly convex result; see
# monostatic_body_generator.py.
#
# Reference shape: the fabricated Gomboc (Domokos & Varkonyi;
# gomboc.eu). See also Wolfram MathWorld, "Gomboc".

