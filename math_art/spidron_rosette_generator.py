# Triangle Spiral Rosette -- planar spidron figures and tilings.
#
# The two-dimensional half of the spidron family: the nested-polygon
# subdivision itself, single spiralling arms, rosettes assembled from
# several arms, and plane tilings of the result.  The three-dimensional
# halves are `spidron_nest_generator` (the folded relief) and
# `spidron_ball_generator` (spidronised polyhedra); all three share
# `spidron_math`.
#
# WHAT IS DRAWN.  Take a regular m-gon and connect alternate vertices; a
# smaller m-gon appears inside, scaled by cos(ag)/cos(ag/2) and turned
# by ag/2, where ag = 360/m.  The annulus between the two triangulates
# into 2m triangles, and repeating the step fills the m-gon with a
# spiral of ever-smaller triangles.  At m = 6 the two triangles per step
# are exactly the 120-degree isosceles and the equilateral triangle of
# Erdely's original spidron, and the ratio is 1/sqrt(3).
#
# A single limb of that figure is a "semi-spidron", or arm.  Following
# Gangopadhyay, the arm comes in three flavours that differ only in how
# fast the limb's index advances from ring to ring -- fixed (spidron),
# every ring (creeper), every second ring (ladder, whose index step
# therefore spans four triangles and squares the scale ratio).  Arms are
# then placed round a regular n-gon, wound outward, inward, or both
# superimposed, and the result can be tiled across the plane.
#
# Output goes through the shared Pattern Engine, so grout margin, relief
# height, per-tile materials and separate-tile output all come for free.
#
# References:
# - Daniel Erdely, "Some Surprising New Properties of the Spidrons",
#   Bridges 2005 Conference Proceedings, pp. 179-186 -- the figure and
#   its hexagonal nest.
# - T. Gangopadhyay, "On an Alternate Construction Method for
#   Generating Spidrons and New Tiling Patterns Generated by them",
#   International Journal of Computer Applications 160(3), 2017,
#   pp. 25-29 -- m-part arms assembled into a regular polygon, and the
#   tilings drawn from them.
# - T. Gangopadhyay, "On New Polygonal Designs Constructed using
#   Spidrons and New Tiling Patterns Generated by Them", International
#   Journal of Computer Applications 162(1), 2017, pp. 11-15 -- the
#   clockwise, anti-clockwise and superimposed rosettes.
# - T. Gangopadhyay, "On Subdividing Regular Polygons using Structures
#   other than Spidrons and Tiling Patterns Generated by Them",
#   International Journal of Computer Applications 163(2), 2017,
#   pp. 9-12 -- the "ladder" variant.
# - T. Gangopadhyay, "On further Subdivisions of Regular Polygons using
#   Structures other than Spidrons and Tiling Patterns Generated by
#   them", International Journal of Computer Applications 165(1), 2017,
#   pp. 31-34 -- the "creeper" variant.
# - Mihaly Hujter, "A csillaghatszog spidronszeru felgyurodese mogotti
#   matematika", Haladvany Kiadvany, 16 June 2018 -- the kite
#   similarity that fixes the 1/sqrt(3) scale and 30-degree turn.

