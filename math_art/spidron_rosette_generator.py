        def _execute_nest(self, context):
            """One catalogued nest: its boundary, spidronised.

            Most nests are SKEW, so this is not a planar rosette -- the
            boundary comes from `spidron_nests`, which reconstructs it
            from the published angle sequence as a circuit of Universal
            Node branches."""
            code = self.nest
            pts = sn.oriented(code)
            if pts is None:
                self.report({'ERROR'}, "cannot construct nest %s" % code)
                return {'CANCELLED'}
            loop = np.asarray(pts, float)
            verts, faces, mats = sm.spidronise(
                loop, float(self.nest_step), float(self.nest_twist),
                int(self.rings), cap=self.cap_center)
            # spidronise emits (annulus, corner, two triangles) in that
            # order, so ring and arm indices come straight from the
            # triangle index -- the same colourings the Full Figure
            # offers, on the same footing.
            m = len(loop)
            per_ring = 2 * m
            npal = len(pc.PALETTE_RGBA)
            ring_of, arm_of = [], []
            for t in range(len(faces)):
                if mats[t] == 2:                 # centre cap
                    ring_of.append(int(self.rings))
                    arm_of.append(t % m)
                else:
                    ring_of.append(t // per_ring)
                    arm_of.append((t % per_ring) // 2)
            if self.color_by == 'ARM':
                ncol = max(2, min(int(self.colors), npal))
                mats = [arm_of[t] % ncol for t in range(len(faces))]
            elif self.color_by == 'RING':
                mats = [ring_of[t] % npal for t in range(len(faces))]
            elif self.color_by == 'UNIFORM':
                mats = [0] * len(faces)
            # SHAPE keeps spidronise's own 0/1/2 labelling
            obj = pc.build_object(context, "Spidron Nest %s" % code,
                                  [tuple(v) for v in verts],
                                  [tuple(f) for f in faces], list(mats),
                                  span=2.0, fit=True)
            if obj is None:
                self.report({'ERROR'}, "no geometry generated")
                return {'CANCELLED'}
            n, group, sym, angles = sn.NESTS[code]
            self.report({'INFO'},
                        "Nest %s: %d-gon, %s, %s, %d rings%s"
                        % (code, n, group, sym, int(self.rings),
                           "" if group == 'flat' else " (skew)"))
            return {'FINISHED'}

        def execute(self, context):
            if self.layout_kind == 'NEST':
                return self._execute_nest(context)
            m, n = int(self.arm_parts), int(self.corners)
            polys, kinds, rix, aix = build_polys(
                self.layout_kind, m, n, int(self.rings), self.arm,
                self.winding, int(self.tiles_x), int(self.tiles_y),
                self.motif)
            if not polys:
                self.report({'ERROR'}, "no triangles generated")
                return {'CANCELLED'}
            if (self.layout_kind == 'TILING' and self.motif == 'FIGURE'
                    and m != 6):
                self.report({'WARNING'},
                            "only six arm parts tile the plane without "
                            "gaps; built a spaced grid")
            npal = len(pc.PALETTE_RGBA)
            if self.color_by == 'ARM':
                types = arm_materials(aix, npal, int(self.colors))
                cby = 'TYPE'
            elif self.color_by == 'RING':
                types = [r % npal for r in rix]
                cby = 'TYPE'
            elif self.color_by == 'SHAPE':
                types = [k % 2 for k in kinds]
                cby = 'TYPE'
            else:
                types = [0] * len(polys)
                cby = 'UNIFORM'
            cells = tg.cells_from_polys(
                lambda a, b: (polys, types), 1, 1, cby,
                self.margin, self.height, False)
            if (self.winding == 'BOTH' and self.height <= 0.0
                    and self.layout_kind in ('ROSETTE', 'TILING')
                    and not (self.layout_kind == 'TILING'
                             and self.motif == 'FIGURE')):
                # the superimposed design lays the two windings in one
                # plane; a hair of separation keeps the flat faces from
                # z-fighting where they overlap (relief height already
                # separates them when it is nonzero)
                lift = 0.003
                for ci, a in enumerate(aix):
                    if a >= n:
                        cv, cf, cm = cells[ci]
                        cells[ci] = ([(x, y, z + lift)
                                      for (x, y, z) in cv], cf, cm)
            obj = pc.emit(context, "Spidron Rosette", cells,
                          self.separate, fit=True, operator=self)
            if obj is None:
                self.report({'ERROR'}, "no geometry generated")
                return {'CANCELLED'}
            obj["math_art_pattern"] = True
            self.report({'INFO'}, "%s  m=%d  %d arms  %d triangles"
                        % (self.layout_kind.title(), m,
                           len(set(aix)), len(polys)))
            return {'FINISHED'}

