def _poly_area(p):
    a = 0.0
    for i in range(len(p)):
        x0, y0 = p[i]
        x1, y1 = p[(i + 1) % len(p)]
        a += x0 * y1 - x1 * y0
    return 0.5 * a


def _tri_key(t, nd=9):
    return tuple(sorted((round(x, nd), round(y, nd)) for (x, y) in t))


def _selftest():
    ok = True

    def chk(name, cond, extra=""):
        nonlocal ok
        ok = ok and bool(cond)
        print("  %-52s %s %s" % (name, "OK" if cond else "BAD", extra))

    print("spidron_rosette: layouts")
    for lay in ('FIGURE', 'ARM', 'ROSETTE', 'TILING'):
        p, k, r, a = build_polys(lay, 6, 6, 6, 'SPIDRON', 'OUT', 2, 2)
        chk("%-8s builds triangles" % lay,
            len(p) > 0 and all(len(q) == 3 for q in p),
            "%d tris" % len(p))
        chk("%-8s labels align with polys" % lay,
            len(p) == len(k) == len(r) == len(a))
        chk("%-8s ring index spans the rings" % lay,
            max(r) + 1 == 6, "max ring %d" % max(r))
        chk("%-8s every triangle is counterclockwise" % lay,
            all(_poly_area(q) > 1e-12 for q in p))

    # counts are exactly predictable
    p, _, _, a = build_polys('FIGURE', 6, 6, 5, 'SPIDRON', 'OUT', 1, 1)
    chk("full figure = 2*m per ring", len(p) == 2 * 6 * 5, "%d" % len(p))
    chk("full figure carries m arms of 2 tris per ring",
        sorted(set(a)) == list(range(6))
        and all(a.count(j) == 2 * 5 for j in range(6)))
    p, _, _, a = build_polys('ARM', 8, 6, 7, 'SPIDRON', 'OUT', 1, 1)
    chk("arm = 2 per ring, one arm", len(p) == 2 * 7 and set(a) == {0},
        "%d" % len(p))
    p, _, _, a = build_polys('ROSETTE', 6, 5, 4, 'SPIDRON', 'BOTH', 1, 1)
    chk("BOTH winding doubles the rosette", len(p) == 2 * 5 * 2 * 4,
        "%d" % len(p))
    chk("BOTH carries 2n distinct arms", sorted(set(a)) == list(range(10)))
    p, _, _, a = build_polys('TILING', 6, 6, 3, 'SPIDRON', 'OUT', 3, 2)
    chk("tiling repeats the rosette", len(p) == 6 * (6 * 2 * 3),
        "%d" % len(p))

    print("spidron_rosette: the figure is its arms")
    # the full figure assembled arm by arm must be EXACTLY the nested-
    # polygon subdivision, whichever arm kind does the grouping -- the
    # three kinds are three ways of cutting one figure into m limbs.
    for m in (5, 6, 9):
        ref, _ = sm.full_figure_polys(m, 6)
        want = sorted(_tri_key(t) for t in ref)
        for arm in sm.ARM_KINDS:
            p, _, _, a = build_polys('FIGURE', m, 6, 6, arm, 'OUT', 1, 1)
            got = sorted(_tri_key(t) for t in p)
            chk("m=%d %-8s arms partition the figure" % (m, arm),
                got == want and len(set(a)) == m)

    print("spidron_rosette: geometry")
    for m in (5, 6, 8, 12):
        p, _, _, _ = build_polys('FIGURE', m, 6, 4, 'SPIDRON', 'OUT', 1, 1)
        chk("m=%2d every triangle has positive area" % m,
            all(_poly_area(q) > 1e-12 for q in p))
    p, _, _, _ = build_polys('FIGURE', 6, 6, 8, 'SPIDRON', 'OUT', 1, 1)
    tot = sum(abs(_poly_area(q)) for q in p)
    R = 1.0
    outer = 0.5 * 6 * R * R * sin(2 * pi / 6)
    inner_R = R * sm.arm_ratio(6) ** 8
    inner = 0.5 * 6 * inner_R * inner_R * sin(2 * pi / 6)
    chk("figure tiles the polygon minus its core",
        abs(tot - (outer - inner)) < 1e-12, "%.2e" % abs(tot - (outer - inner)))

    for arm in sm.ARM_KINDS:
        p, _, _, _ = build_polys('ARM', 6, 6, 8, arm, 'OUT', 1, 1)
        chk("%-8s arm builds" % arm, len(p) == 16)
        linked = all(
            len(set(_tri_key(p[i])) & set(_tri_key(p[i + 1]))) >= 1
            for i in range(len(p) - 1))
        chk("%-8s arm is a linked chain" % arm, linked)
    a1, _, _, _ = build_polys('ARM', 6, 6, 6, 'SPIDRON', 'OUT', 1, 1)
    a2, _, _, _ = build_polys('ARM', 6, 6, 6, 'CREEPER', 'OUT', 1, 1)
    chk("arms are genuinely different figures",
        max(abs(np.array(a1[6]) - np.array(a2[6])).max(), 0.0) > 1e-6)

    # the papers' scale laws: an index step of the spidron/creeper is
    # one ring pair scaled by cos(ag)/cos(ag/2); the ladder's unit
    # spans two rings and four triangles and SQUARES that ratio.
    def perim(t):
        return sum(hypot(t[i][0] - t[(i + 1) % 3][0],
                         t[i][1] - t[(i + 1) % 3][1]) for i in range(3))

    for arm, stride, want in (('SPIDRON', 2, sm.arm_ratio(8)),
                              ('CREEPER', 2, sm.arm_ratio(8)),
                              ('LADDER', 4, sm.arm_ratio(8) ** 2)):
        p, _, _, _ = build_polys('ARM', 8, 6, 8, arm, 'OUT', 1, 1)
        r = perim(p[stride]) / perim(p[0])
        chk("%-8s unit scales by ratio%s" % (arm,
            "^2" if stride == 4 else "  "),
            abs(r - want) < 1e-12, "%.9f" % r)

    print("spidron_rosette: the rosette is a wreath")
    for (m, n) in ((6, 6), (6, 8), (8, 5)):
        V = sm.rosette_ngon(m, n)
        p, _, _, a = build_polys('ROSETTE', m, n, 5, 'SPIDRON', 'OUT',
                                 1, 1)
        L = 2.0 * sin(pi / m)
        side = np.linalg.norm(np.array(V[1]) - np.array(V[0]))
        chk("m=%d n=%d polygon side = arm base edge" % (m, n),
            abs(side - L) < 1e-12)
        # each arm sits on its own polygon edge, entirely outside it
        good_base = good_out = True
        for j in range(n):
            tris = [t for t, ai in zip(p, a) if ai == j]
            Vj, Vj1 = np.array(V[j]), np.array(V[(j + 1) % n])
            ex = (Vj1 - Vj) / side
            nout = np.array([ex[1], -ex[0]])
            base = {tuple(np.round(v, 9)) for v in (Vj, Vj1)}
            first = {tuple(np.round(v, 9)) for v in tris[0][:2]}
            good_base = good_base and first == base
            for t in tris:
                for v in t:
                    if float((np.array(v) - Vj) @ nout) < -1e-9:
                        good_out = False
        chk("m=%d n=%d arms sit on the polygon edges" % (m, n), good_base)
        chk("m=%d n=%d arms stay outside the polygon" % (m, n), good_out)
    # IN is OUT mirrored edge for edge
    po, _, _, ao = build_polys('ROSETTE', 6, 6, 5, 'SPIDRON', 'OUT', 1, 1)
    pb, _, _, ab = build_polys('ROSETTE', 6, 6, 5, 'SPIDRON', 'BOTH', 1, 1)
    V = np.array(sm.rosette_ngon(6, 6))
    j = 0
    Vj, Vj1 = V[j], V[(j + 1) % 6]
    mid = 0.5 * (Vj + Vj1)
    ax = (Vj1 - Vj) / np.linalg.norm(Vj1 - Vj)   # reflection axis normal
    out_j = [t for t, ai in zip(pb, ab) if ai == j]
    in_j = [t for t, ai in zip(pb, ab) if ai == 6 + j]
    mirror_ok = len(out_j) == len(in_j) > 0
    for to, ti in zip(out_j, in_j):
        ref = set()
        for vo in to:
            q = np.array(vo) - mid
            q = q - 2.0 * float(q @ ax) * ax
            ref.add(tuple(np.round(q + mid, 9)))
        got = {tuple(np.round(v, 9)) for v in ti}
        mirror_ok = mirror_ok and ref == got
    chk("IN arm = OUT arm reflected on its edge", mirror_ok)
    chk("OUT alone matches the OUT half of BOTH",
        all(_tri_key(a_) == _tri_key(b_) for a_, b_ in
            zip(po, [t for t, ai in zip(pb, ab) if ai < 6])))

    print("spidron_rosette: tiling and colouring")
    p1, _, _, _ = build_polys('ROSETTE', 6, 6, 4, 'SPIDRON', 'OUT', 1, 1)
    xs = [x for q in p1 for (x, _) in q]
    ys = [y for q in p1 for (_, y) in q]
    w, h = max(xs) - min(xs), max(ys) - min(ys)
    pt, _, _, _ = build_polys('TILING', 6, 6, 4, 'SPIDRON', 'OUT', 3, 2)
    xs2 = [x for q in pt for (x, _) in q]
    ys2 = [y for q in pt for (_, y) in q]
    chk("tiling pitch is the rosette's bounding box",
        abs((max(xs2) - min(xs2)) - 3 * w) < 1e-9
        and abs((max(ys2) - min(ys2)) - 2 * h) < 1e-9)
    per = len(p1)
    minx, miny = min(xs2), min(ys2)
    overlap = False
    for ti in range(6):
        iy, ix = divmod(ti, 3)
        for q in pt[ti * per:(ti + 1) * per]:
            for (x, y) in q:
                if not (ix * w - 1e-9 <= x - minx <= (ix + 1) * w + 1e-9
                        and iy * h - 1e-9 <= y - miny
                        <= (iy + 1) * h + 1e-9):
                    overlap = True
    chk("each tile stays in its own lattice cell", not overlap)

    npal = len(pc.PALETTE_RGBA)
    for count in (2, 6, npal, npal + 1, 2 * npal, 2 * npal + 1):
        mats = arm_materials(list(range(count)), npal)
        ring_ok = all(mats[i] != mats[(i + 1) % count]
                      for i in range(count)) or count == 1
        chk("colour-by-arm: %2d arms, neighbours differ" % count,
            ring_ok and max(mats) < npal)
    _, _, _, a = build_polys('FIGURE', 13, 6, 3, 'SPIDRON', 'OUT', 1, 1)
    mats = arm_materials(a, npal)
    chk("13-arm figure: last arm avoids the first's colour",
        mats[0] != mats[-1] and len(set(mats)) <= npal)

    # the Colors cap: two-tone pinwheels, and honest odd-count seams
    for count in (4, 6, 8, 12):
        mats = arm_materials(list(range(count)), npal, 2)
        chk("two colours alternate round %2d arms" % count,
            max(mats) <= 1
            and all(mats[i] != mats[(i + 1) % count]
                    for i in range(count)))
    for count in (5, 7, 13):
        # an odd cycle is not 2-colourable: exactly ONE adjacent pair
        # may match, never more, and the cap must still hold
        mats = arm_materials(list(range(count)), npal, 2)
        seams = sum(mats[i] == mats[(i + 1) % count]
                    for i in range(count))
        chk("two colours round %2d arms leave one seam" % count,
            max(mats) <= 1 and seams == 1)
    for cap in (3, 5, 12):
        mats = arm_materials(list(range(12)), npal, cap)
        chk("colour cap %2d respected, neighbours differ" % cap,
            max(mats) < cap
            and all(mats[i] != mats[(i + 1) % 12] for i in range(12)))

    print("spidron_rosette: the figure motif tiles the plane")
    pf, kf, rf, af = build_polys('TILING', 6, 6, 4, 'SPIDRON', 'OUT',
                                 3, 3, motif='FIGURE')
    chk("figure tiling repeats the filled hexagon",
        len(pf) == 9 * 2 * 6 * 4, "%d tris" % len(pf))
    # neighbouring hexagons must share their corner vertices EXACTLY
    # (round to 1e-9): each tile's six ring-0 outer corners, matched
    # across every edge-adjacent pair of the honeycomb lattice.
    per = len(pf) // 9
    tile_corners = []
    for t in range(9):
        cs = set()
        for q, kk, rr in zip(pf[t * per:(t + 1) * per],
                             kf[t * per:(t + 1) * per],
                             rf[t * per:(t + 1) * per]):
            if rr == 0 and kk == 0:
                cs.add((round(q[0][0], 9), round(q[0][1], 9)))
                cs.add((round(q[1][0], 9), round(q[1][1], 9)))
        tile_corners.append(cs)
    chk("each figure tile has six outer corners",
        all(len(c) == 6 for c in tile_corners))
    # lattice coordinates of the offset-column walk: tile (ix, iy) sits
    # at ix * u + (iy - ix//2) * v with u = (3R/2, sqrt3 R/2) and
    # v = (0, sqrt3 R); edge-adjacency is a unit lattice step
    idx = {(ix, iy - ix // 2): iy * 3 + ix
           for iy in range(3) for ix in range(3)}
    share_ok, npairs = True, 0
    for (i, j), t in idx.items():
        for (di, dj) in ((1, 0), (0, 1), (1, -1)):
            t2 = idx.get((i + di, j + dj))
            if t2 is None:
                continue
            npairs += 1
            if len(tile_corners[t] & tile_corners[t2]) != 2:
                share_ok = False
    chk("neighbouring hexagons share an edge exactly",
        share_ok and npairs == 16, "%d adjacent pairs" % npairs)
    # gapless coverage: sample a disk spanning the central tile and its
    # crossings into all six neighbours; every point must be covered by
    # EXACTLY one triangle.  (The open spiral cores are excluded: any
    # finite ring count leaves a hexagonal core of radius ratio^rings,
    # which is the construction, not a gap.)
    pf6, _k6, _r6, _a6 = build_polys('TILING', 6, 6, 6, 'SPIDRON',
                                     'OUT', 3, 3, motif='FIGURE')
    pitch = 2.0 * cos(pi / 6.0)
    centres = [(1.5 * (ix - 1.0),
                pitch * (iy - 1.0) + 0.5 * pitch * (ix % 2))
               for iy in range(3) for ix in range(3)]
    ccx, ccy = centres[4]                    # the central tile
    core = sm.arm_ratio(6) ** 6
    boxes = []
    for q in pf6:
        xs = [x for (x, _) in q]
        ys = [y for (_, y) in q]
        boxes.append((q, min(xs), max(xs), min(ys), max(ys)))
    tested = bad = 0
    for ixp in range(41):
        for iyp in range(41):
            x = ccx - 1.1 + 2.2 * ixp / 40.0 + 0.0137
            y = ccy - 1.1 + 2.2 * iyp / 40.0 + 0.0071
            if (x - ccx) ** 2 + (y - ccy) ** 2 > 1.1 * 1.1:
                continue
            if any((x - cx) ** 2 + (y - cy) ** 2 < (2.0 * core) ** 2
                   for cx, cy in centres):
                continue
            cnt = 0
            for q, x0, x1, y0, y1 in boxes:
                if x0 <= x <= x1 and y0 <= y <= y1 and tg._pip(q, x, y):
                    cnt += 1
            tested += 1
            if cnt != 1:
                bad += 1
    chk("figure tiling covers the plane, no gaps or overlaps",
        tested > 400 and bad == 0,
        "%d sampled, %d bad" % (tested, bad))
    # any other arm count cannot tile: the fallback still builds, as an
    # honest spaced grid of the m-gon figure
    p5, _, _, _ = build_polys('TILING', 5, 6, 3, 'SPIDRON', 'OUT', 2, 2,
                              motif='FIGURE')
    chk("figure motif falls back for m != 6",
        len(p5) == 4 * 2 * 5 * 3)

    print("RESULT:", "OK" if ok else "BAD")
    return ok
