def _ccw(tri):
    """The triangle with positive signed area, so every emitted face
    points up regardless of any mirroring in the assembly."""
    (x0, y0), (x1, y1), (x2, y2) = tri
    a = (x1 - x0) * (y2 - y0) - (x2 - x0) * (y1 - y0)
    return list(tri) if a >= 0.0 else [tri[0], tri[2], tri[1]]


def arm_materials(arm_ix, npal, colors=None):
    """Material index per triangle for colour-by-arm.

    Cycles the palette -- capped to the first `colors` entries when
    given, e.g. 2 for Kaplan's two-tone pinwheel -- over the arms in
    order.  When the arm count is one more than a multiple of the
    cycle, the cycle is shortened by one so the last arm never matches
    the first: neighbouring arms always read as different colours.
    The one case where that guarantee is impossible is a two-colour
    cycle round an ODD number of arms (an odd cycle is not
    2-colourable), so there the shortening is skipped and exactly one
    adjacent pair matches."""
    ids = sorted(set(arm_ix))
    if not ids:
        return []
    per = max(2, min(npal, colors if colors else npal))
    if len(ids) > 1 and (len(ids) - 1) % per == 0 and per > 2:
        per -= 1
    rank = {a: i for i, a in enumerate(ids)}
    return [rank[a] % per for a in arm_ix]


def build_polys(layout, m, n, rings, arm, winding, tiles_x, tiles_y,
                motif='WREATH'):
    """Return (polys, kinds, ring_ix, arm_ix) in the plane for the
    chosen layout: triangle vertex lists (counterclockwise), the 0/1
    triangle shape, the ring each triangle belongs to, and the arm it
    is part of.  Ring and arm are carried for every layout, so
    colour-by-ring and colour-by-arm work everywhere -- the full
    figure is assembled from its m arms rather than ring by ring
    precisely so that arm identity survives.

    `motif` applies to TILING only: WREATH repeats the rosette on a
    bounding-box grid; FIGURE repeats the filled polygon, and at m = 6
    places the hexagons on the honeycomb lattice so neighbours share
    their edges exactly and the plane is covered with no gaps."""
    if layout == 'FIGURE':
        polys, kinds, rix, aix = [], [], [], []
        for j in range(m):
            for i, (t, k) in enumerate(sm.arm_polys(m, rings, arm, j)):
                polys.append(_ccw(t))
                kinds.append(k)
                rix.append(i // 2)
                aix.append(j)
        return polys, kinds, rix, aix
    if layout == 'ARM':
        tris = sm.arm_polys(m, rings, arm, 0)
        return ([_ccw(t) for t, _ in tris], [k for _, k in tris],
                [i // 2 for i in range(len(tris))], [0] * len(tris))
    if layout == 'ROSETTE':
        polys, kinds, rix, aix = sm.rosette_polys(m, n, rings, arm,
                                                  winding)
        return [_ccw(p) for p in polys], kinds, rix, aix

    base_layout = 'FIGURE' if motif == 'FIGURE' else 'ROSETTE'
    polys, kinds, rix, aix = build_polys(base_layout, m, n, rings, arm,
                                         winding, 1, 1)
    offsets = []
    if motif == 'FIGURE' and m == 6:
        # THE CLASSIC SPIDRON TILING.  The filled hexagon (circumradius
        # 1, a vertex at angle 0) tiles the plane on the honeycomb
        # lattice: neighbouring centres one double-apothem apart
        # (2 cos(pi/6) = sqrt 3), along the edge-normal directions 30,
        # 90 and 150 degrees.  The patch walks that lattice in offset
        # columns -- column pitch 3R/2, row pitch sqrt(3) R, odd
        # columns raised half a row -- so a Columns x Rows patch reads
        # as a roughly rectangular block.  On this lattice the
        # hexagons' corner vertices coincide EXACTLY (verified in
        # `_selftest`), so adjacent tiles share whole edges and the
        # spiral arms cover the plane with no background showing.
        pitch = 2.0 * cos(pi / 6.0)
        for iy in range(tiles_y):
            for ix in range(tiles_x):
                offsets.append((1.5 * (ix - 0.5 * (tiles_x - 1)),
                                pitch * (iy - 0.5 * (tiles_y - 1))
                                + 0.5 * pitch * (ix % 2)))
    else:
        # lattice pitch: the motif's own bounding box, so copies pack
        # edge to edge -- touching where the motif reaches its box,
        # never overlapping.  (An m-gon with m != 6 cannot tile the
        # plane, so the FIGURE motif also lands here: an honest spaced
        # grid rather than a fake tiling.)
        xs = [x for p in polys for (x, _) in p]
        ys = [y for p in polys for (_, y) in p]
        sx, sy = max(xs) - min(xs), max(ys) - min(ys)
        for iy in range(tiles_y):
            for ix in range(tiles_x):
                offsets.append(((ix - 0.5 * (tiles_x - 1)) * sx,
                                (iy - 0.5 * (tiles_y - 1)) * sy))
    out_p, out_k, out_r, out_a = [], [], [], []
    for (dx, dy) in offsets:
        for p, k, r, a in zip(polys, kinds, rix, aix):
            out_p.append([(x + dx, y + dy) for (x, y) in p])
            out_k.append(k)
            out_r.append(r)
            out_a.append(a)
    return out_p, out_k, out_r, out_a


