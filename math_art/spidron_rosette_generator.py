if _IN_BLENDER:

    class MESH_OT_spidron_rosette_add(bpy.types.Operator, AddObjectHelper):
        """Add a spidron figure: a spiral of triangles filling a
        regular polygon, as a single arm, a rosette or a tiling"""
        bl_idname = "mesh.spidron_rosette_add"
        bl_label = "Triangle Spiral Rosette"
        bl_options = {'REGISTER', 'UNDO'}

        layout_kind: EnumProperty(
            name="Layout", items=LAYOUT_ITEMS, default='FIGURE',
            description="What to build: the whole polygon subdivision, "
                        "one arm, a rosette of arms, or a tiling")
        arm: EnumProperty(
            name="Arm", items=ARM_ITEMS, default='SPIDRON',
            description="Which limb of the spidron family to draw")
        arm_parts: IntProperty(
            name="Arm Parts", default=6, min=5, max=24,
            description="Sides of the polygon the arm subdivides; the "
                        "arm angle is 360 divided by this. Five is the "
                        "smallest that gives a shrinking spiral, six is "
                        "the classical hexagonal spidron")
        corners: IntProperty(
            name="Corners", default=6, min=3, max=24,
            description="How many arms are placed round the rosette. "
                        "Independent of Arm Parts")
        rings: IntProperty(
            name="Rings", default=10, min=1, max=24,
            description="How many times the spiral step repeats. Each "
                        "ring is smaller than the last, so beyond about "
                        "sixteen the additions are invisible")
        winding: EnumProperty(
            name="Winding", items=WINDING_ITEMS, default='OUT',
            description="Sense in which the arms are wound round the "
                        "rosette")
        tiles_x: IntProperty(
            name="Columns", default=3, min=1, max=12,
            description="Rosettes across the tiling")
        tiles_y: IntProperty(
            name="Rows", default=3, min=1, max=12,
            description="Rosettes down the tiling")
        color_by: EnumProperty(
            name="Color", default='SHAPE',
            items=[('SHAPE', "Triangle Shape",
                    "One material per triangle shape, so the two "
                    "shapes of each ring read differently"),
                   ('RING', "Ring", "One material per ring, showing "
                                    "the spiral banding"),
                   ('UNIFORM', "Uniform", "A single material")],
            description="How materials are assigned")
        margin: FloatProperty(
            name="Margin", default=0.0, min=0.0, max=0.4,
            description="Inset each triangle by this fraction, leaving "
                        "a grout gap between tiles")
        height: FloatProperty(
            name="Height", default=0.0, min=0.0, max=2.0,
            description="Extrude each triangle to this depth; zero "
                        "leaves a flat pattern")
        separate: BoolProperty(
            name="Separate Tiles", default=False,
            description="Build one object per triangle under a parent "
                        "empty instead of a single merged mesh")

        def execute(self, context):
            m, n = int(self.arm_parts), int(self.corners)
            polys, types, rix = build_polys(
                self.layout_kind, m, n, int(self.rings), self.arm,
                self.winding, int(self.tiles_x), int(self.tiles_y))
            if not polys:
                self.report({'ERROR'}, "no triangles generated")
                return {'CANCELLED'}
            if self.color_by == 'RING':
                npal = len(pc.PALETTE_RGBA)
                types = [r % npal for r in rix]
                cby = 'TYPE'
            elif self.color_by == 'SHAPE':
                types = [t % 2 for t in types]
                cby = 'TYPE'
            else:
                types = [0] * len(polys)
                cby = 'UNIFORM'
            cells = tg.cells_from_polys(
                lambda a, b: (polys, types), 1, 1, cby,
                self.margin, self.height, False)
            obj = pc.emit(context, "Spidron Rosette", cells,
                          self.separate, fit=True, operator=self)
            if obj is None:
                self.report({'ERROR'}, "no geometry generated")
                return {'CANCELLED'}
            obj["math_art_pattern"] = True
            self.report({'INFO'}, "%s  m=%d  %d triangles"
                        % (self.layout_kind.title(), m, len(polys)))
            return {'FINISHED'}

        def draw(self, context):
            lay = self.layout
            lay.use_property_split = True
            lay.prop(self, 'layout_kind')
            lay.prop(self, 'arm_parts')
            if self.layout_kind != 'FIGURE':
                lay.prop(self, 'arm')
            if self.layout_kind in ('ROSETTE', 'TILING'):
                lay.prop(self, 'corners')
                lay.prop(self, 'winding')
            lay.prop(self, 'rings')
            if self.layout_kind == 'TILING':
                lay.prop(self, 'tiles_x')
                lay.prop(self, 'tiles_y')
            for p in ('color_by', 'margin', 'height'):
                lay.prop(self, p)
            lay.prop(self, 'separate')
            lay.prop(self, 'align')

    def _menu_func(self, context):
        self.layout.operator("mesh.spidron_rosette_add",
                             icon='FORCE_VORTEX')

